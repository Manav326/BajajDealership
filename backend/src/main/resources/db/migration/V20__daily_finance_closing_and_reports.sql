-- Immutable, dealership-scoped daily finance closing snapshots.
-- Balances are reconciled against saved ledger events; external bank/UPI settlement is not verified.
create table daily_finance_close (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  business_date date not null,
  notes varchar(1000),
  closed_by_staff_user_id bigint not null,
  closed_at timestamptz not null default now(),
  unique (dealership_id, business_date),
  unique (dealership_id, id),
  constraint fk_daily_finance_close_actor_same_dealership
    foreign key (dealership_id, closed_by_staff_user_id)
    references staff_user(dealership_id, id)
);
create index ix_daily_finance_close_history on daily_finance_close(dealership_id,business_date desc);

create table daily_finance_close_channel (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null,
  close_id bigint not null,
  payment_method varchar(24) not null check(payment_method in ('CASH','UPI','BANK_TRANSFER','CARD','OTHER')),
  opening_balance numeric(16,2) not null default 0 check(opening_balance >= 0),
  recorded_collections numeric(16,2) not null default 0 check(recorded_collections >= 0),
  payment_reversals numeric(16,2) not null default 0 check(payment_reversals >= 0),
  approved_expenses numeric(16,2) not null default 0 check(approved_expenses >= 0),
  expense_reversals numeric(16,2) not null default 0 check(expense_reversals >= 0),
  expected_closing numeric(16,2) not null,
  counted_closing numeric(16,2) not null check(counted_closing >= 0),
  variance numeric(16,2) not null,
  unique(dealership_id,close_id,payment_method),
  constraint fk_daily_finance_close_channel_header
    foreign key(dealership_id,close_id) references daily_finance_close(dealership_id,id)
);
insert into permission(code,description) values
 ('finance.close.read','View daily finance closing and reconciliation snapshots')
 on conflict(code) do nothing;
insert into role_permission(role_id,permission_id)
 select r.id,p.id from role r join permission p on p.code='finance.close.read'
 where r.code in ('OWNER','MANAGER','CASHIER') on conflict do nothing;
