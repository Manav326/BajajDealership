alter table dealership_license
  add column max_desktop_devices integer not null default 5
    check (max_desktop_devices between 1 and 100);

create table dealership_license_device (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership_license(dealership_id) on delete cascade,
  installation_hash char(64) not null,
  display_name varchar(120) not null default 'Lucky Bajaj Desktop',
  app_version varchar(40),
  status varchar(20) not null default 'ACTIVE' check (status in ('ACTIVE', 'REVOKED')),
  first_activated_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  revoked_at timestamptz,
  last_changed_reason varchar(500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, installation_hash)
);

create index ix_license_device_active
  on dealership_license_device (dealership_id, status, last_seen_at desc);

alter table staff_session
  add column desktop_installation_hash char(64);

alter table staff_session
  add constraint fk_staff_session_desktop_installation
  foreign key (dealership_id, desktop_installation_hash)
  references dealership_license_device (dealership_id, installation_hash);
