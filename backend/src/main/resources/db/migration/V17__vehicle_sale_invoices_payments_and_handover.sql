-- Operational vehicle-sale invoicing, payment records and acknowledged handover.
-- This is not a GST tax invoice or an external payment-provider integration.

insert into permission (code, description) values
  ('sales.invoice', 'Create and issue operational vehicle-sale invoices'),
  ('sales.payment', 'Record operational vehicle-sale payments and receipts'),
  ('sales.payment.reverse', 'Reverse vehicle-sale payment records before delivery with an audited reason')
on conflict (code) do nothing;

insert into role_permission (role_id, permission_id)
select r.id, p.id
from role r join permission p on p.code in (
  'sales.invoice', 'sales.payment', 'sales.payment.reverse', 'sales.deliver'
)
where r.code in ('OWNER', 'MANAGER')
on conflict do nothing;

insert into role_permission (role_id, permission_id)
select r.id, p.id
from role r join permission p on p.code in ('sales.invoice', 'sales.deliver')
where r.code = 'SALES_EXECUTIVE'
on conflict do nothing;

insert into role_permission (role_id, permission_id)
select r.id, p.id
from role r join permission p on p.code in ('sales.invoice', 'sales.payment')
where r.code = 'CASHIER'
on conflict do nothing;

create table vehicle_sale_invoice (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  invoice_number varchar(48) not null,
  booking_id bigint not null,
  customer_id bigint not null,
  vehicle_unit_id bigint not null,
  status varchar(16) not null default 'DRAFT'
    check (status in ('DRAFT', 'ISSUED', 'CANCELLED')),
  subtotal numeric(14,2) not null check (subtotal > 0),
  discount_amount numeric(14,2) not null default 0 check (discount_amount >= 0),
  invoice_total numeric(14,2) not null check (invoice_total > 0),
  request_fingerprint char(64) not null,
  customer_message varchar(2000),
  created_by_staff_user_id bigint not null,
  issued_by_staff_user_id bigint,
  issued_at timestamptz,
  cancelled_by_staff_user_id bigint,
  cancelled_at timestamptz,
  cancellation_reason varchar(500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, invoice_number),
  unique (dealership_id, id),
  unique (dealership_id, request_fingerprint, booking_id),
  check (discount_amount <= subtotal),
  check (invoice_total = subtotal - discount_amount),
  check (
    (status = 'DRAFT' and issued_at is null and issued_by_staff_user_id is null
      and cancelled_at is null and cancelled_by_staff_user_id is null)
    or (status = 'ISSUED' and issued_at is not null and issued_by_staff_user_id is not null
      and cancelled_at is null and cancelled_by_staff_user_id is null)
    or (status = 'CANCELLED' and cancelled_at is not null and cancelled_by_staff_user_id is not null
      and cancellation_reason is not null)
  ),
  constraint fk_vehicle_sale_invoice_booking_same_dealership
    foreign key (dealership_id, booking_id) references sales_booking(dealership_id, id),
  constraint fk_vehicle_sale_invoice_customer_same_dealership
    foreign key (dealership_id, customer_id) references customer(dealership_id, id),
  constraint fk_vehicle_sale_invoice_unit_same_dealership
    foreign key (dealership_id, vehicle_unit_id) references vehicle_unit(dealership_id, id),
  constraint fk_vehicle_sale_invoice_creator_same_dealership
    foreign key (dealership_id, created_by_staff_user_id) references staff_user(dealership_id, id),
  constraint fk_vehicle_sale_invoice_issuer_same_dealership
    foreign key (dealership_id, issued_by_staff_user_id) references staff_user(dealership_id, id),
  constraint fk_vehicle_sale_invoice_canceller_same_dealership
    foreign key (dealership_id, cancelled_by_staff_user_id) references staff_user(dealership_id, id)
);

create unique index uq_vehicle_sale_invoice_active_booking
  on vehicle_sale_invoice (dealership_id, booking_id)
  where status in ('DRAFT', 'ISSUED');
create index ix_vehicle_sale_invoice_status
  on vehicle_sale_invoice (dealership_id, status, created_at desc);

create table vehicle_sale_invoice_line (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  invoice_id bigint not null,
  line_number integer not null check (line_number > 0),
  line_type varchar(16) not null check (line_type in ('VEHICLE', 'ACCESSORY', 'OTHER')),
  description varchar(300) not null,
  quantity numeric(12,3) not null check (quantity > 0),
  unit_price numeric(14,2) not null check (unit_price >= 0),
  line_total numeric(14,2) not null check (line_total >= 0),
  created_at timestamptz not null default now(),
  unique (dealership_id, invoice_id, line_number),
  constraint fk_vehicle_sale_line_invoice_same_dealership
    foreign key (dealership_id, invoice_id) references vehicle_sale_invoice(dealership_id, id)
);
create unique index uq_vehicle_sale_invoice_vehicle_line
  on vehicle_sale_invoice_line (dealership_id, invoice_id)
  where line_type = 'VEHICLE';
create index ix_vehicle_sale_invoice_lines
  on vehicle_sale_invoice_line (dealership_id, invoice_id, line_number);

create table vehicle_sale_payment (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  receipt_number varchar(48) not null,
  idempotency_key varchar(120) not null,
  request_fingerprint char(64) not null,
  payment_method varchar(24) not null
    check (payment_method in ('CASH', 'UPI', 'BANK_TRANSFER', 'CARD', 'OTHER')),
  amount numeric(14,2) not null check (amount > 0),
  payment_reference varchar(160),
  note varchar(1000),
  status varchar(16) not null default 'RECORDED'
    check (status in ('RECORDED', 'REVERSED')),
  recorded_by_staff_user_id bigint not null,
  recorded_at timestamptz not null default now(),
  reversed_by_staff_user_id bigint,
  reversed_at timestamptz,
  created_at timestamptz not null default now(),
  unique (dealership_id, receipt_number),
  unique (dealership_id, idempotency_key),
  unique (dealership_id, id),
  check (
    (status = 'RECORDED' and reversed_by_staff_user_id is null and reversed_at is null)
    or (status = 'REVERSED' and reversed_by_staff_user_id is not null and reversed_at is not null)
  ),
  constraint fk_vehicle_sale_payment_recorder_same_dealership
    foreign key (dealership_id, recorded_by_staff_user_id) references staff_user(dealership_id, id),
  constraint fk_vehicle_sale_payment_reverser_same_dealership
    foreign key (dealership_id, reversed_by_staff_user_id) references staff_user(dealership_id, id)
);
create index ix_vehicle_sale_payment_history
  on vehicle_sale_payment (dealership_id, recorded_at desc);

create table vehicle_sale_payment_allocation (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  payment_id bigint not null,
  invoice_id bigint not null,
  amount numeric(14,2) not null check (amount > 0),
  allocated_by_staff_user_id bigint not null,
  allocated_at timestamptz not null default now(),
  unique (dealership_id, payment_id),
  constraint fk_vehicle_sale_payment_allocation_payment
    foreign key (dealership_id, payment_id) references vehicle_sale_payment(dealership_id, id),
  constraint fk_vehicle_sale_payment_allocation_invoice
    foreign key (dealership_id, invoice_id) references vehicle_sale_invoice(dealership_id, id),
  constraint fk_vehicle_sale_payment_allocation_actor
    foreign key (dealership_id, allocated_by_staff_user_id) references staff_user(dealership_id, id)
);
create index ix_vehicle_sale_payment_allocation_invoice
  on vehicle_sale_payment_allocation (dealership_id, invoice_id, allocated_at desc);

create table vehicle_sale_payment_reversal (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  payment_id bigint not null,
  reason varchar(500) not null,
  external_reference varchar(160),
  reversed_by_staff_user_id bigint not null,
  reversed_at timestamptz not null default now(),
  unique (dealership_id, payment_id),
  constraint fk_vehicle_sale_payment_reversal_payment
    foreign key (dealership_id, payment_id) references vehicle_sale_payment(dealership_id, id),
  constraint fk_vehicle_sale_payment_reversal_actor
    foreign key (dealership_id, reversed_by_staff_user_id) references staff_user(dealership_id, id)
);

create table vehicle_sale_handover (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  booking_id bigint not null,
  invoice_id bigint not null,
  customer_id bigint not null,
  vehicle_unit_id bigint not null,
  delivered_to_name varchar(160) not null,
  customer_acknowledged boolean not null check (customer_acknowledged),
  acknowledgement_method varchar(24) not null
    check (acknowledgement_method in ('IN_PERSON', 'SIGNED_FORM', 'OTP_REFERENCE', 'WRITTEN_MESSAGE')),
  acknowledgement_reference varchar(160),
  note varchar(1000),
  delivered_by_staff_user_id bigint not null,
  delivered_at timestamptz not null default now(),
  unique (dealership_id, booking_id),
  unique (dealership_id, invoice_id),
  unique (dealership_id, vehicle_unit_id),
  constraint fk_vehicle_sale_handover_booking
    foreign key (dealership_id, booking_id) references sales_booking(dealership_id, id),
  constraint fk_vehicle_sale_handover_invoice
    foreign key (dealership_id, invoice_id) references vehicle_sale_invoice(dealership_id, id),
  constraint fk_vehicle_sale_handover_customer
    foreign key (dealership_id, customer_id) references customer(dealership_id, id),
  constraint fk_vehicle_sale_handover_unit
    foreign key (dealership_id, vehicle_unit_id) references vehicle_unit(dealership_id, id),
  constraint fk_vehicle_sale_handover_actor
    foreign key (dealership_id, delivered_by_staff_user_id) references staff_user(dealership_id, id),
  check (
    (acknowledgement_method not in ('SIGNED_FORM', 'OTP_REFERENCE'))
    or acknowledgement_reference is not null
  )
);
create index ix_vehicle_sale_handover_history
  on vehicle_sale_handover (dealership_id, delivered_at desc);
