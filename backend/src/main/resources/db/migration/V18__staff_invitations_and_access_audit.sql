-- Single-use staff activation tokens are stored only as hashes.
create table staff_invitation (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  staff_user_id bigint not null,
  token_hash char(64) not null unique,
  issued_by_staff_user_id bigint not null,
  expires_at timestamptz not null,
  accepted_at timestamptz,
  revoked_at timestamptz,
  created_at timestamptz not null default now(),
  unique (dealership_id, id),
  constraint fk_staff_invitation_staff_same_dealership
    foreign key (dealership_id, staff_user_id) references staff_user(dealership_id, id),
  constraint fk_staff_invitation_issuer_same_dealership
    foreign key (dealership_id, issued_by_staff_user_id) references staff_user(dealership_id, id),
  check (expires_at > created_at),
  check (accepted_at is null or revoked_at is null)
);

create unique index uq_staff_pending_invitation
  on staff_invitation (dealership_id, staff_user_id)
  where accepted_at is null and revoked_at is null;

create index ix_staff_invitation_expiry
  on staff_invitation (expires_at)
  where accepted_at is null and revoked_at is null;
