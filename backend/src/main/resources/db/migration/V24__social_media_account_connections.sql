-- Social publishing account links are dealership-scoped. OAuth state is hashed, short-lived and one-use.
insert into permission (code, description) values
  ('social_media.read', 'View connected social accounts and publishing status'),
  ('social_media.manage', 'Connect social accounts and manage social publishing')
on conflict (code) do nothing;

insert into role_permission (role_id, permission_id)
select r.id, p.id
from role r cross join permission p
where r.code in ('OWNER', 'MANAGER')
  and p.code in ('social_media.read', 'social_media.manage')
on conflict do nothing;

create table social_media_oauth_state (
  state_hash char(64) primary key,
  dealership_id bigint not null references dealership(id),
  staff_user_id bigint not null,
  expires_at timestamptz not null,
  consumed_at timestamptz,
  created_at timestamptz not null default now(),
  constraint fk_social_oauth_state_staff_same_dealership
    foreign key (dealership_id, staff_user_id)
    references staff_user (dealership_id, id),
  check (expires_at > created_at)
);
create index ix_social_media_oauth_state_expiry
  on social_media_oauth_state (expires_at)
  where consumed_at is null;

create table social_media_connection (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  provider varchar(20) not null check (provider in ('META')),
  provider_user_id varchar(160) not null,
  provider_user_name varchar(200),
  user_access_token_ciphertext text not null,
  token_expires_at timestamptz,
  status varchar(20) not null default 'ACTIVE'
    check (status in ('ACTIVE', 'DISCONNECTED', 'EXPIRED', 'ERROR')),
  connected_by_staff_user_id bigint not null,
  connected_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint uq_social_media_connection_provider_user
    unique (dealership_id, provider, provider_user_id),
  constraint uq_social_media_connection_id_dealership unique (id, dealership_id),
  constraint fk_social_media_connection_actor_same_dealership
    foreign key (dealership_id, connected_by_staff_user_id)
    references staff_user (dealership_id, id)
);
create index ix_social_media_connection_status
  on social_media_connection (dealership_id, provider, status);

create table social_media_destination (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  connection_id bigint not null,
  provider varchar(20) not null check (provider in ('META')),
  destination_type varchar(32) not null
    check (destination_type in ('FACEBOOK_PAGE', 'INSTAGRAM_PROFESSIONAL')),
  provider_destination_id varchar(160) not null,
  parent_page_provider_id varchar(160),
  display_name varchar(200) not null,
  username varchar(160),
  page_access_token_ciphertext text not null,
  token_expires_at timestamptz,
  status varchar(20) not null default 'ACTIVE'
    check (status in ('ACTIVE', 'DISCONNECTED', 'EXPIRED', 'ERROR')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint uq_social_media_destination_provider_id
    unique (dealership_id, provider, destination_type, provider_destination_id),
  constraint fk_social_destination_connection_same_dealership
    foreign key (connection_id, dealership_id)
    references social_media_connection (id, dealership_id)
);
create index ix_social_media_destination_active
  on social_media_destination (dealership_id, provider, destination_type, status);

create table social_media_audit (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  actor_staff_user_id bigint,
  connection_id bigint,
  destination_id bigint,
  provider varchar(20) not null check (provider in ('META')),
  action varchar(80) not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint fk_social_media_audit_actor_same_dealership
    foreign key (dealership_id, actor_staff_user_id)
    references staff_user (dealership_id, id),
  constraint fk_social_media_audit_connection_same_dealership
    foreign key (connection_id, dealership_id)
    references social_media_connection (id, dealership_id),
  constraint fk_social_media_audit_destination_same_dealership
    foreign key (destination_id, dealership_id)
    references social_media_destination (id, dealership_id)
);
create index ix_social_media_audit_dealership_created
  on social_media_audit (dealership_id, created_at desc);
