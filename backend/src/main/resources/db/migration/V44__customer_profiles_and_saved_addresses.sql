-- Customer-owned profile information and multiple saved delivery destinations.
-- Purchase and payment records intentionally remain immutable and independent of editable addresses.
create table customer_address (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null,
  customer_id bigint not null,
  label varchar(16) not null check (label in ('HOME','WORK','OTHER')),
  recipient_name varchar(160) not null,
  phone varchar(32) not null,
  address_line1 varchar(240) not null,
  address_line2 varchar(240),
  landmark varchar(160),
  locality varchar(160),
  city varchar(120) not null,
  district varchar(120),
  state varchar(120) not null,
  postal_code varchar(12) not null,
  country varchar(80) not null default 'India',
  is_default_delivery boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, id),
  constraint fk_customer_address_customer_same_dealership
    foreign key (dealership_id, customer_id) references customer(dealership_id, id) on delete cascade
);
create index ix_customer_address_owner
  on customer_address (dealership_id, customer_id, is_default_delivery desc, updated_at desc);
create unique index uq_customer_default_delivery_address
  on customer_address (dealership_id, customer_id) where is_default_delivery = true;

-- Profile images are private to the owning customer session and dealership staff permissions.
create table customer_profile_photo (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null,
  customer_id bigint not null,
  content_type varchar(32) not null check (content_type in ('image/jpeg','image/png','image/webp')),
  image_bytes bytea not null,
  byte_length integer not null check (byte_length between 1 and 2097152),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, customer_id),
  constraint fk_customer_profile_photo_customer_same_dealership
    foreign key (dealership_id, customer_id) references customer(dealership_id, id) on delete cascade,
  constraint ck_customer_profile_photo_length
    check (octet_length(image_bytes) = byte_length)
);
