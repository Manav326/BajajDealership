create table notification_template (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  template_family_id uuid not null default gen_random_uuid(),
  dealership_id bigint not null references dealership(id),
  template_name varchar(120) not null,
  description varchar(500),
  content_version integer not null default 1 check (content_version > 0),
  content_document jsonb not null,
  status varchar(20) not null default 'DRAFT' check (status in ('DRAFT', 'VALIDATED', 'ACTIVE', 'ARCHIVED')),
  created_by_staff_user_id bigint references staff_user(id),
  updated_by_staff_user_id bigint references staff_user(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (template_family_id, content_version),
  check (jsonb_typeof(content_document) = 'object'),
  check ((content_document ->> 'version') = '1'),
  check (jsonb_typeof(content_document -> 'blocks') = 'array')
);
create index ix_notification_template_owner on notification_template (dealership_id, status, lower(template_name));

create table notification_campaign (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  created_by_staff_user_id bigint not null references staff_user(id),
  scope varchar(20) not null check (scope in ('CUSTOMER', 'STAFF', 'DEALERSHIP')),
  title varchar(120) not null,
  summary varchar(300),
  audience_filter jsonb not null default '{}'::jsonb,
  audience_snapshot jsonb not null default '{}'::jsonb,
  content_document jsonb not null,
  template_id bigint references notification_template(id),
  template_version integer,
  status varchar(24) not null default 'DRAFT'
    check (status in ('DRAFT', 'PREVIEWED', 'SCHEDULED', 'QUEUED', 'PROCESSING', 'SENT', 'PARTIALLY_FAILED', 'FAILED', 'CANCELLED', 'EXPIRED')),
  idempotency_key varchar(120) not null,
  request_fingerprint char(64),
  preview_token_hash char(64),
  preview_fingerprint char(64),
  preview_expires_at timestamptz,
  preview_consumed_at timestamptz,
  scheduled_at timestamptz,
  expires_at timestamptz,
  resolved_recipient_count integer not null default 0 check (resolved_recipient_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  dispatched_at timestamptz,
  cancelled_at timestamptz,
  unique (dealership_id, created_by_staff_user_id, idempotency_key),
  check ((content_document ->> 'version') = '1'),
  check (jsonb_typeof(content_document -> 'blocks') = 'array'),
  check (expires_at is null or scheduled_at is null or expires_at > scheduled_at)
);
create index ix_notification_campaign_schedule on notification_campaign (status, scheduled_at) where status = 'SCHEDULED';
create index ix_notification_campaign_dealership on notification_campaign (dealership_id, created_at desc);

create table notification_recipient (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  campaign_id bigint not null references notification_campaign(id) on delete cascade,
  dealership_id bigint not null references dealership(id),
  recipient_kind varchar(12) not null check (recipient_kind in ('CUSTOMER', 'STAFF')),
  customer_id bigint references customer(id),
  staff_user_id bigint references staff_user(id),
  status varchar(20) not null default 'QUEUED' check (status in ('QUEUED', 'IN_APP_CREATED', 'READ', 'DISMISSED', 'FAILED')),
  created_at timestamptz not null default now(),
  read_at timestamptz,
  dismissed_at timestamptz,
  check (
    (recipient_kind = 'CUSTOMER' and customer_id is not null and staff_user_id is null)
    or (recipient_kind = 'STAFF' and staff_user_id is not null and customer_id is null)
  )
);
create unique index uq_notification_recipient_customer on notification_recipient (campaign_id, customer_id) where customer_id is not null;
create unique index uq_notification_recipient_staff on notification_recipient (campaign_id, staff_user_id) where staff_user_id is not null;
create index ix_notification_inbox_customer on notification_recipient (dealership_id, customer_id, created_at desc) where customer_id is not null;
create index ix_notification_inbox_staff on notification_recipient (dealership_id, staff_user_id, created_at desc) where staff_user_id is not null;

create table notification_device_registration (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  customer_id bigint references customer(id),
  staff_user_id bigint references staff_user(id),
  platform varchar(20) not null check (platform in ('ANDROID')),
  app_version varchar(40),
  device_token_ciphertext text not null,
  device_token_hash char(64) not null,
  status varchar(16) not null default 'ACTIVE' check (status in ('ACTIVE', 'REVOKED', 'INVALID')),
  last_seen_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  revoked_at timestamptz,
  check (
    (customer_id is not null and staff_user_id is null)
    or (customer_id is null and staff_user_id is not null)
  )
);
create unique index uq_notification_device_token_hash on notification_device_registration (device_token_hash);
create index ix_notification_device_customer on notification_device_registration (dealership_id, customer_id, status) where customer_id is not null;
create index ix_notification_device_staff on notification_device_registration (dealership_id, staff_user_id, status) where staff_user_id is not null;

create table notification_delivery_attempt (
  id bigint generated by default as identity primary key,
  recipient_id bigint not null references notification_recipient(id) on delete cascade,
  channel varchar(20) not null check (channel in ('IN_APP', 'ANDROID_PUSH', 'SMS', 'WHATSAPP', 'EMAIL')),
  device_registration_id bigint references notification_device_registration(id),
  status varchar(20) not null default 'PENDING' check (status in ('PENDING', 'PROCESSING', 'SENT', 'DELIVERED', 'RETRYING', 'FAILED', 'NOT_CONFIGURED')),
  attempt_number integer not null default 0 check (attempt_number >= 0),
  next_attempt_at timestamptz not null default now(),
  provider_message_id varchar(200),
  failure_code varchar(100),
  attempted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (channel = 'ANDROID_PUSH' or device_registration_id is null)
);
create unique index uq_notification_delivery_channel_device on notification_delivery_attempt (recipient_id, channel, coalesce(device_registration_id, 0));
create index ix_notification_delivery_queue on notification_delivery_attempt (next_attempt_at, id) where status in ('PENDING', 'RETRYING');

create table notification_media_asset (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  created_by_staff_user_id bigint references staff_user(id),
  asset_kind varchar(20) not null check (asset_kind in ('IMAGE', 'VIDEO', 'ANIMATION')),
  mime_type varchar(100) not null,
  byte_length bigint not null check (byte_length > 0),
  sha256 char(64) not null,
  width integer,
  height integer,
  duration_ms bigint,
  storage_key varchar(500) not null unique,
  alt_text varchar(500),
  decorative boolean not null default false,
  status varchar(16) not null default 'ACTIVE' check (status in ('PROCESSING', 'ACTIVE', 'REJECTED', 'ARCHIVED')),
  created_at timestamptz not null default now(),
  check (decorative or asset_kind = 'VIDEO' or nullif(trim(alt_text), '') is not null)
);

create table notification_audit (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  actor_staff_user_id bigint references staff_user(id),
  campaign_id bigint references notification_campaign(id),
  template_id bigint references notification_template(id),
  action varchar(80) not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index ix_notification_audit_dealership_created on notification_audit (dealership_id, created_at desc);

create table outbox_event (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  event_key varchar(200) not null,
  event_type varchar(100) not null,
  aggregate_type varchar(100) not null,
  aggregate_id varchar(100) not null,
  payload jsonb not null,
  status varchar(20) not null default 'PENDING' check (status in ('PENDING', 'PROCESSING', 'COMPLETED', 'RETRYING', 'FAILED')),
  attempt_count integer not null default 0 check (attempt_count >= 0),
  next_attempt_at timestamptz not null default now(),
  last_error_code varchar(100),
  created_at timestamptz not null default now(),
  processed_at timestamptz,
  unique (dealership_id, event_key)
);
create index ix_outbox_event_queue on outbox_event (next_attempt_at, id) where status in ('PENDING', 'RETRYING');
