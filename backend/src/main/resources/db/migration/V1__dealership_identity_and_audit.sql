create table dealership (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  code varchar(40) not null unique,
  name varchar(160) not null,
  timezone varchar(80) not null default 'Asia/Kolkata',
  status varchar(20) not null default 'ACTIVE' check (status in ('ACTIVE', 'SUSPENDED', 'CLOSED')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table staff_user (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  full_name varchar(160) not null,
  email varchar(320),
  phone varchar(32),
  password_hash varchar(255) not null,
  status varchar(20) not null default 'INVITED' check (status in ('INVITED', 'ACTIVE', 'LOCKED', 'DISABLED')),
  last_login_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (email is not null or phone is not null)
);
create unique index uq_staff_email_per_dealership on staff_user (dealership_id, lower(email)) where email is not null;
create unique index uq_staff_phone_per_dealership on staff_user (dealership_id, phone) where phone is not null;
create index ix_staff_dealership_status on staff_user (dealership_id, status);

create table role (
  id bigint generated by default as identity primary key,
  code varchar(60) not null unique,
  display_name varchar(120) not null,
  is_system_role boolean not null default true,
  created_at timestamptz not null default now()
);
create table permission (
  id bigint generated by default as identity primary key,
  code varchar(100) not null unique,
  description varchar(300) not null
);
create table staff_user_role (
  staff_user_id bigint not null references staff_user(id) on delete cascade,
  role_id bigint not null references role(id),
  assigned_by_staff_user_id bigint references staff_user(id),
  assigned_at timestamptz not null default now(),
  primary key (staff_user_id, role_id)
);
create table role_permission (
  role_id bigint not null references role(id) on delete cascade,
  permission_id bigint not null references permission(id) on delete cascade,
  primary key (role_id, permission_id)
);

create table customer (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  customer_code varchar(40) not null,
  full_name varchar(160) not null,
  phone varchar(32),
  alternate_phone varchar(32),
  email varchar(320),
  preferred_language varchar(12) not null default 'hi' check (preferred_language in ('hi', 'en', 'hinglish')),
  marketing_consent_at timestamptz,
  marketing_consent_source varchar(80),
  status varchar(20) not null default 'ACTIVE' check (status in ('ACTIVE', 'INACTIVE', 'BLOCKED')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, customer_code),
  check (phone is not null or email is not null)
);
create index ix_customer_phone_per_dealership on customer (dealership_id, phone);
create index ix_customer_name_per_dealership on customer (dealership_id, lower(full_name));

create table vehicle_model (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  model_code varchar(60) not null,
  model_name varchar(160) not null,
  variant_name varchar(120),
  colour_name varchar(80),
  model_year integer check (model_year is null or model_year between 1990 and 2200),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, model_code, variant_name, colour_name, model_year)
);
create table vehicle_unit (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  vehicle_model_id bigint not null references vehicle_model(id),
  chassis_number varchar(100) not null,
  engine_number varchar(100) not null,
  stock_status varchar(24) not null default 'AVAILABLE'
    check (stock_status in ('EXPECTED', 'AVAILABLE', 'RESERVED', 'SOLD', 'RETURNED', 'DAMAGED')),
  received_at timestamptz,
  supplier_reference varchar(120),
  purchase_cost numeric(14,2) check (purchase_cost is null or purchase_cost >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, chassis_number),
  unique (dealership_id, engine_number)
);
create index ix_vehicle_stock on vehicle_unit (dealership_id, stock_status, vehicle_model_id);

create table customer_vehicle (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  customer_id bigint not null references customer(id),
  vehicle_unit_id bigint not null references vehicle_unit(id),
  ownership_started_at timestamptz not null default now(),
  ownership_ended_at timestamptz,
  linked_by_staff_user_id bigint references staff_user(id),
  created_at timestamptz not null default now(),
  check (ownership_ended_at is null or ownership_ended_at >= ownership_started_at)
);
create unique index uq_current_customer_vehicle_owner on customer_vehicle (vehicle_unit_id) where ownership_ended_at is null;
create index ix_customer_vehicle_history on customer_vehicle (dealership_id, customer_id, ownership_started_at desc);

create table audit_event (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  actor_kind varchar(20) not null check (actor_kind in ('STAFF', 'CUSTOMER', 'SYSTEM')),
  actor_staff_user_id bigint references staff_user(id),
  actor_customer_id bigint references customer(id),
  action varchar(100) not null,
  entity_type varchar(100) not null,
  entity_id varchar(100),
  reason varchar(500),
  details jsonb not null default '{}'::jsonb,
  request_id varchar(100),
  created_at timestamptz not null default now(),
  check (
    (actor_kind = 'STAFF' and actor_staff_user_id is not null and actor_customer_id is null)
    or (actor_kind = 'CUSTOMER' and actor_customer_id is not null and actor_staff_user_id is null)
    or (actor_kind = 'SYSTEM' and actor_customer_id is null and actor_staff_user_id is null)
  )
);
create index ix_audit_dealership_created on audit_event (dealership_id, created_at desc);
create index ix_audit_entity on audit_event (dealership_id, entity_type, entity_id);
