-- Separate consumable spare parts from individually tracked motorcycle units.
-- Every quantity mutation is transactional and leaves an immutable movement record.

insert into permission (code, description) values
  ('parts.read', 'Read dealership spare-part catalogue, balances and job-card reservations'),
  ('parts.manage', 'Create and maintain the dealership spare-part catalogue and suppliers'),
  ('parts.receive', 'Record spare-part supplier receipts into stock'),
  ('parts.reserve', 'Reserve available spare parts for a workshop job card'),
  ('parts.issue', 'Issue reserved spare parts to workshop work'),
  ('parts.return', 'Return unused issued spare parts or release unused reservations')
on conflict (code) do nothing;

insert into role_permission (role_id, permission_id)
select r.id, p.id
from role r join permission p on p.code in (
  'parts.read', 'parts.manage', 'parts.receive', 'parts.reserve', 'parts.issue', 'parts.return'
)
where r.code in ('OWNER', 'MANAGER')
on conflict do nothing;

insert into role_permission (role_id, permission_id)
select r.id, p.id
from role r join permission p on p.code in ('parts.read', 'parts.receive', 'parts.reserve')
where r.code = 'SERVICE_ADVISOR'
on conflict do nothing;

insert into role_permission (role_id, permission_id)
select r.id, p.id
from role r join permission p on p.code in ('parts.read', 'parts.issue', 'parts.return')
where r.code = 'MECHANIC'
on conflict do nothing;

create table part_supplier (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  supplier_code varchar(48) not null,
  supplier_name varchar(180) not null,
  contact_name varchar(160),
  phone varchar(32),
  email varchar(320),
  address varchar(1000),
  notes varchar(1000),
  active boolean not null default true,
  created_by_staff_user_id bigint not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, supplier_code),
  unique (dealership_id, id),
  constraint fk_part_supplier_creator_same_dealership
    foreign key (dealership_id, created_by_staff_user_id) references staff_user(dealership_id, id)
);
create index ix_part_supplier_search
  on part_supplier (dealership_id, active, lower(supplier_name));

create table spare_part (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  sku_code varchar(60) not null,
  part_name varchar(200) not null,
  description varchar(1000),
  unit_of_measure varchar(16) not null default 'EACH'
    check (unit_of_measure in ('EACH', 'PAIR', 'SET', 'LITRE', 'ML', 'GRAM', 'KG', 'METER')),
  active boolean not null default true,
  created_by_staff_user_id bigint not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, sku_code),
  unique (dealership_id, id),
  constraint fk_spare_part_creator_same_dealership
    foreign key (dealership_id, created_by_staff_user_id) references staff_user(dealership_id, id)
);
create index ix_spare_part_search
  on spare_part (dealership_id, active, lower(part_name));

create table spare_part_balance (
  dealership_id bigint not null references dealership(id),
  part_id bigint not null,
  quantity_on_hand numeric(12,3) not null default 0 check (quantity_on_hand >= 0),
  quantity_reserved numeric(12,3) not null default 0 check (quantity_reserved >= 0),
  average_unit_cost numeric(14,2) not null default 0 check (average_unit_cost >= 0),
  updated_at timestamptz not null default now(),
  primary key (dealership_id, part_id),
  constraint fk_spare_part_balance_part_same_dealership
    foreign key (dealership_id, part_id) references spare_part(dealership_id, id),
  check (quantity_reserved <= quantity_on_hand)
);

create table part_purchase_receipt (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  receipt_number varchar(48) not null,
  supplier_id bigint not null,
  supplier_reference varchar(160),
  idempotency_key varchar(120) not null,
  request_fingerprint char(64) not null,
  status varchar(16) not null default 'RECEIVED' check (status in ('RECEIVED')),
  total_cost numeric(16,2) not null check (total_cost >= 0),
  notes varchar(1000),
  received_by_staff_user_id bigint not null,
  received_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique (dealership_id, receipt_number),
  unique (dealership_id, id),
  unique (dealership_id, idempotency_key),
  constraint fk_part_receipt_supplier_same_dealership
    foreign key (dealership_id, supplier_id) references part_supplier(dealership_id, id),
  constraint fk_part_receipt_receiver_same_dealership
    foreign key (dealership_id, received_by_staff_user_id) references staff_user(dealership_id, id)
);
create index ix_part_purchase_receipt_history
  on part_purchase_receipt (dealership_id, received_at desc);

create table part_purchase_receipt_line (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  receipt_id bigint not null,
  line_number integer not null check (line_number > 0),
  part_id bigint not null,
  quantity numeric(12,3) not null check (quantity > 0),
  unit_cost numeric(14,2) not null check (unit_cost >= 0),
  line_total numeric(16,2) not null check (line_total >= 0),
  created_at timestamptz not null default now(),
  unique (dealership_id, receipt_id, line_number),
  constraint fk_part_receipt_line_receipt_same_dealership
    foreign key (dealership_id, receipt_id) references part_purchase_receipt(dealership_id, id),
  constraint fk_part_receipt_line_part_same_dealership
    foreign key (dealership_id, part_id) references spare_part(dealership_id, id)
);
create index ix_part_receipt_line_part_history
  on part_purchase_receipt_line (dealership_id, part_id, created_at desc);

create table service_job_part_reservation (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  reservation_code varchar(48) not null,
  job_card_id bigint not null,
  part_id bigint not null,
  quantity_reserved numeric(12,3) not null check (quantity_reserved > 0),
  quantity_issued numeric(12,3) not null default 0 check (quantity_issued >= 0),
  quantity_returned numeric(12,3) not null default 0 check (quantity_returned >= 0),
  unit_cost_snapshot numeric(14,2) not null check (unit_cost_snapshot >= 0),
  status varchar(24) not null default 'OPEN'
    check (status in ('OPEN', 'PARTIALLY_ISSUED', 'ISSUED', 'PARTIALLY_CANCELLED', 'CANCELLED')),
  idempotency_key varchar(120) not null,
  request_fingerprint char(64) not null,
  notes varchar(1000),
  reserved_by_staff_user_id bigint not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, reservation_code),
  unique (dealership_id, id),
  unique (dealership_id, public_id),
  unique (dealership_id, idempotency_key),
  constraint fk_job_part_reservation_job_same_dealership
    foreign key (dealership_id, job_card_id) references service_job_card(dealership_id, id),
  constraint fk_job_part_reservation_part_same_dealership
    foreign key (dealership_id, part_id) references spare_part(dealership_id, id),
  constraint fk_job_part_reservation_actor_same_dealership
    foreign key (dealership_id, reserved_by_staff_user_id) references staff_user(dealership_id, id),
  check (quantity_issued <= quantity_reserved),
  check (quantity_returned <= quantity_issued),
  check (status <> 'OPEN' or quantity_issued = 0),
  check (status <> 'PARTIALLY_ISSUED' or (quantity_issued > 0 and quantity_issued < quantity_reserved)),
  check (status <> 'ISSUED' or quantity_issued = quantity_reserved),
  check (status <> 'PARTIALLY_CANCELLED' or (quantity_issued > 0 and quantity_issued < quantity_reserved)),
  check (status <> 'CANCELLED' or quantity_issued = 0)
);
create index ix_job_part_reservation_job
  on service_job_part_reservation (dealership_id, job_card_id, created_at desc);
create index ix_job_part_reservation_part
  on service_job_part_reservation (dealership_id, part_id, status);

-- One idempotency namespace serializes reserve/issue/return/release writes before balance mutation.
create table spare_part_operation (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  idempotency_key varchar(120) not null,
  request_fingerprint char(64) not null,
  operation_type varchar(16) not null
    check (operation_type in ('RESERVE', 'ISSUE', 'RETURN', 'RELEASE')),
  reservation_public_id uuid,
  actor_staff_user_id bigint not null,
  created_at timestamptz not null default now(),
  unique (dealership_id, idempotency_key),
  constraint fk_spare_part_operation_actor_same_dealership
    foreign key (dealership_id, actor_staff_user_id) references staff_user(dealership_id, id),
  constraint fk_spare_part_operation_reservation_same_dealership
    foreign key (dealership_id, reservation_public_id)
    references service_job_part_reservation(dealership_id, public_id)
);

create table spare_part_stock_movement (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  part_id bigint not null,
  movement_type varchar(32) not null check (movement_type in (
    'PURCHASE_RECEIPT', 'RESERVATION_CREATED', 'RESERVATION_RELEASED',
    'ISSUED_TO_JOB', 'RETURNED_FROM_JOB', 'STOCK_CORRECTION'
  )),
  quantity_delta numeric(12,3) not null,
  reserved_delta numeric(12,3) not null,
  quantity_on_hand_after numeric(12,3) not null check (quantity_on_hand_after >= 0),
  quantity_reserved_after numeric(12,3) not null check (quantity_reserved_after >= 0),
  unit_cost numeric(14,2) not null check (unit_cost >= 0),
  reference_type varchar(40) not null,
  reference_id varchar(100) not null,
  operation_key varchar(160) not null,
  request_fingerprint char(64) not null,
  actor_staff_user_id bigint not null,
  created_at timestamptz not null default now(),
  unique (dealership_id, operation_key),
  constraint fk_spare_part_movement_part_same_dealership
    foreign key (dealership_id, part_id) references spare_part(dealership_id, id),
  constraint fk_spare_part_movement_actor_same_dealership
    foreign key (dealership_id, actor_staff_user_id) references staff_user(dealership_id, id),
  check (quantity_reserved_after <= quantity_on_hand_after)
);
create index ix_spare_part_movement_history
  on spare_part_stock_movement (dealership_id, part_id, created_at desc);
create index ix_spare_part_movement_reference
  on spare_part_stock_movement (dealership_id, reference_type, reference_id);
