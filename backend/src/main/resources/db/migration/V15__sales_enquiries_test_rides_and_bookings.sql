-- Sales pipeline records. Sales reservations reuse vehicle_unit and vehicle_stock_movement.
create table sales_enquiry (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  enquiry_code varchar(48) not null,
  customer_id bigint not null,
  interested_model_id bigint,
  assigned_staff_user_id bigint,
  created_by_staff_user_id bigint not null,
  status varchar(28) not null default 'NEW'
    check (status in ('NEW', 'CONTACTED', 'QUALIFIED', 'TEST_RIDE_SCHEDULED', 'BOOKED', 'LOST', 'CLOSED')),
  lead_source varchar(24) not null
    check (lead_source in ('WALK_IN', 'PHONE', 'WEBSITE', 'REFERRAL', 'CAMPAIGN', 'SOCIAL_MEDIA', 'OTHER')),
  contact_preference varchar(16) not null default 'CALL'
    check (contact_preference in ('CALL', 'SMS', 'WHATSAPP', 'EMAIL', 'IN_PERSON', 'NONE')),
  next_follow_up_at timestamptz,
  last_contacted_at timestamptz,
  notes varchar(2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, enquiry_code),
  unique (dealership_id, id),
  constraint fk_sales_enquiry_customer_same_dealership
    foreign key (dealership_id, customer_id) references customer(dealership_id, id),
  constraint fk_sales_enquiry_model_same_dealership
    foreign key (dealership_id, interested_model_id) references vehicle_model(dealership_id, id),
  constraint fk_sales_enquiry_assignee_same_dealership
    foreign key (dealership_id, assigned_staff_user_id) references staff_user(dealership_id, id),
  constraint fk_sales_enquiry_creator_same_dealership
    foreign key (dealership_id, created_by_staff_user_id) references staff_user(dealership_id, id)
);
create index ix_sales_enquiry_pipeline
  on sales_enquiry (dealership_id, status, updated_at desc);
create index ix_sales_enquiry_follow_up
  on sales_enquiry (dealership_id, next_follow_up_at)
  where next_follow_up_at is not null;
create index ix_sales_enquiry_customer
  on sales_enquiry (dealership_id, customer_id, created_at desc);

create table sales_test_ride (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  test_ride_code varchar(48) not null,
  enquiry_id bigint not null,
  vehicle_unit_id bigint not null,
  scheduled_start timestamptz not null,
  scheduled_end timestamptz not null,
  status varchar(16) not null default 'SCHEDULED'
    check (status in ('SCHEDULED', 'CHECKED_OUT', 'COMPLETED', 'CANCELLED', 'NO_SHOW')),
  notes varchar(1000),
  created_by_staff_user_id bigint not null,
  checked_out_by_staff_user_id bigint,
  checked_out_at timestamptz,
  completed_by_staff_user_id bigint,
  completed_at timestamptz,
  cancelled_by_staff_user_id bigint,
  cancelled_at timestamptz,
  cancellation_reason varchar(500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, test_ride_code),
  unique (dealership_id, id),
  check (scheduled_end > scheduled_start),
  check (
    (status = 'SCHEDULED' and checked_out_at is null and completed_at is null and cancelled_at is null)
    or (status = 'CHECKED_OUT' and checked_out_at is not null and completed_at is null and cancelled_at is null)
    or (status = 'COMPLETED' and checked_out_at is not null and completed_at is not null and cancelled_at is null)
    or (status in ('CANCELLED', 'NO_SHOW') and cancelled_at is not null and cancelled_by_staff_user_id is not null)
  ),
  constraint fk_sales_test_ride_enquiry_same_dealership
    foreign key (dealership_id, enquiry_id) references sales_enquiry(dealership_id, id),
  constraint fk_sales_test_ride_unit_same_dealership
    foreign key (dealership_id, vehicle_unit_id) references vehicle_unit(dealership_id, id),
  constraint fk_sales_test_ride_creator_same_dealership
    foreign key (dealership_id, created_by_staff_user_id) references staff_user(dealership_id, id),
  constraint fk_sales_test_ride_checkout_actor_same_dealership
    foreign key (dealership_id, checked_out_by_staff_user_id) references staff_user(dealership_id, id),
  constraint fk_sales_test_ride_completer_same_dealership
    foreign key (dealership_id, completed_by_staff_user_id) references staff_user(dealership_id, id),
  constraint fk_sales_test_ride_canceller_same_dealership
    foreign key (dealership_id, cancelled_by_staff_user_id) references staff_user(dealership_id, id)
);
create index ix_sales_test_ride_schedule
  on sales_test_ride (dealership_id, scheduled_start, status);
create index ix_sales_test_ride_unit_schedule
  on sales_test_ride (dealership_id, vehicle_unit_id, scheduled_start, scheduled_end);

create table sales_booking (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  booking_code varchar(48) not null,
  enquiry_id bigint not null,
  customer_id bigint not null,
  vehicle_unit_id bigint not null,
  status varchar(20) not null default 'ACTIVE'
    check (status in ('ACTIVE', 'CANCELLED', 'CONVERTED_TO_SALE')),
  notes varchar(1000),
  created_by_staff_user_id bigint not null,
  cancelled_by_staff_user_id bigint,
  created_at timestamptz not null default now(),
  cancelled_at timestamptz,
  cancellation_reason varchar(500),
  updated_at timestamptz not null default now(),
  unique (dealership_id, booking_code),
  unique (dealership_id, id),
  check (
    (status = 'ACTIVE' and cancelled_at is null and cancelled_by_staff_user_id is null)
    or (status = 'CANCELLED' and cancelled_at is not null and cancelled_by_staff_user_id is not null)
    or (status = 'CONVERTED_TO_SALE' and cancelled_at is null)
  ),
  constraint fk_sales_booking_enquiry_same_dealership
    foreign key (dealership_id, enquiry_id) references sales_enquiry(dealership_id, id),
  constraint fk_sales_booking_customer_same_dealership
    foreign key (dealership_id, customer_id) references customer(dealership_id, id),
  constraint fk_sales_booking_unit_same_dealership
    foreign key (dealership_id, vehicle_unit_id) references vehicle_unit(dealership_id, id),
  constraint fk_sales_booking_creator_same_dealership
    foreign key (dealership_id, created_by_staff_user_id) references staff_user(dealership_id, id),
  constraint fk_sales_booking_canceller_same_dealership
    foreign key (dealership_id, cancelled_by_staff_user_id) references staff_user(dealership_id, id)
);
create unique index uq_sales_booking_active_vehicle
  on sales_booking (dealership_id, vehicle_unit_id) where status = 'ACTIVE';
create unique index uq_sales_booking_active_enquiry
  on sales_booking (dealership_id, enquiry_id) where status = 'ACTIVE';
create index ix_sales_booking_pipeline
  on sales_booking (dealership_id, status, created_at desc);

create table sales_enquiry_activity (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  enquiry_id bigint not null,
  activity_type varchar(36) not null
    check (activity_type in (
      'ENQUIRY_CREATED', 'STATUS_CHANGED', 'FOLLOW_UP_SET', 'NOTE_ADDED',
      'TEST_RIDE_SCHEDULED', 'TEST_RIDE_CHECKED_OUT', 'TEST_RIDE_COMPLETED',
      'TEST_RIDE_CANCELLED', 'BOOKING_CREATED', 'BOOKING_CANCELLED'
    )),
  from_status varchar(28),
  to_status varchar(28),
  note varchar(2000),
  follow_up_at timestamptz,
  reference_type varchar(32),
  reference_id varchar(100),
  actor_staff_user_id bigint not null,
  created_at timestamptz not null default now(),
  constraint fk_sales_activity_enquiry_same_dealership
    foreign key (dealership_id, enquiry_id) references sales_enquiry(dealership_id, id),
  constraint fk_sales_activity_actor_same_dealership
    foreign key (dealership_id, actor_staff_user_id) references staff_user(dealership_id, id)
);
create index ix_sales_enquiry_activity_timeline
  on sales_enquiry_activity (dealership_id, enquiry_id, created_at desc, id desc);
