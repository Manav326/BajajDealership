create table staff_session (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  staff_user_id bigint not null references staff_user(id),
  token_hash char(64) not null unique,
  issued_at timestamptz not null default now(),
  expires_at timestamptz not null,
  last_seen_at timestamptz not null default now(),
  revoked_at timestamptz,
  user_agent varchar(300),
  remote_address_hash char(64),
  check (expires_at > issued_at),
  constraint fk_staff_session_identity_same_dealership
    foreign key (dealership_id, staff_user_id)
    references staff_user (dealership_id, id)
);
create index ix_staff_session_active
  on staff_session (staff_user_id, expires_at desc)
  where revoked_at is null;

create table auth_login_attempt (
  id bigint generated by default as identity primary key,
  login_key_hash char(64) not null,
  remote_address_hash char(64) not null,
  succeeded boolean not null,
  attempted_at timestamptz not null default now()
);
create index ix_auth_login_attempt_login
  on auth_login_attempt (login_key_hash, attempted_at desc);
create index ix_auth_login_attempt_remote
  on auth_login_attempt (remote_address_hash, attempted_at desc);

