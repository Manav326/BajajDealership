-- The catalogue seeds model definitions, never fictitious physical stock units.
-- Existing and newly bootstrapped dealerships receive model rows for enquiry/booking linkage.
insert into vehicle_model(dealership_id, model_code, model_name, variant_name, colour_name, model_year, active)
select d.id, c.model_code, c.model_name, null, null, null, true
from dealership d
cross join bajaj_catalogue_model c
where d.status = 'ACTIVE' and c.active
  and not exists (
    select 1 from vehicle_model vm
    where vm.dealership_id = d.id and vm.model_code = c.model_code
  );
