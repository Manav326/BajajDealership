-- Public product specifications are catalogue metadata; physical stock remains in vehicle_model/vehicle_unit.
-- Bajaj-only constraint is intentional: the Lucky Bajaj motorcycle showroom must never surface another marque.
create table bajaj_catalogue_model (
  model_code varchar(60) primary key,
  manufacturer varchar(24) not null default 'BAJAJ' check (manufacturer = 'BAJAJ'),
  model_name varchar(160) not null,
  family varchar(60) not null,
  category varchar(32) not null check (category in ('COMMUTER','STREET','SPORT','TOURING','CRUISER','RUGGED')),
  engine_cc numeric(7,2) not null check (engine_cc > 0),
  max_power varchar(80) not null,
  max_torque varchar(80) not null,
  gearbox varchar(80),
  braking varchar(160),
  front_suspension varchar(160),
  rear_suspension varchar(160),
  fuel_tank_l numeric(5,2),
  ground_clearance_mm integer,
  kerb_weight_kg numeric(6,2),
  ride_character varchar(120) not null,
  highlights text[] not null default array[]::text[],
  hero_image_url text not null,
  official_model_url text not null,
  official_specs_url text not null,
  ex_showroom_price numeric(14,2) check (ex_showroom_price is null or ex_showroom_price > 0),
  price_city varchar(80) not null default 'New Delhi',
  price_source_url text not null,
  price_verified_at date,
  active boolean not null default true,
  featured_rank integer not null default 100,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index ix_bajaj_catalogue_active_featured
  on bajaj_catalogue_model(active, featured_rank, model_name);

