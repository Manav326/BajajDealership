-- Operational workshop billing records. These are not tax-compliant GST invoices.
-- Tax fields and statutory invoice rendering remain out of scope until requirements are confirmed.

create table service_invoice (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  invoice_number varchar(48) not null,
  job_card_id bigint not null,
  estimate_id bigint not null,
  estimate_revision integer not null check (estimate_revision > 0),
  status varchar(16) not null default 'DRAFT'
    check (status in ('DRAFT', 'ISSUED', 'CANCELLED')),
  parts_subtotal numeric(14,2) not null check (parts_subtotal >= 0),
  labour_subtotal numeric(14,2) not null check (labour_subtotal >= 0),
  other_subtotal numeric(14,2) not null check (other_subtotal >= 0),
  discount_amount numeric(14,2) not null default 0 check (discount_amount >= 0),
  invoice_total numeric(14,2) not null check (invoice_total >= 0),
  customer_message varchar(2000),
  created_by_staff_user_id bigint not null,
  issued_by_staff_user_id bigint,
  issued_at timestamptz,
  cancelled_by_staff_user_id bigint,
  cancelled_at timestamptz,
  cancellation_reason varchar(500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, invoice_number),
  unique (dealership_id, id),
  constraint fk_service_invoice_job_card_same_dealership
    foreign key (dealership_id, job_card_id)
    references service_job_card(dealership_id, id),
  constraint fk_service_invoice_estimate_same_dealership
    foreign key (dealership_id, estimate_id)
    references service_estimate(dealership_id, id),
  constraint fk_service_invoice_creator_same_dealership
    foreign key (dealership_id, created_by_staff_user_id)
    references staff_user(dealership_id, id),
  constraint fk_service_invoice_issuer_same_dealership
    foreign key (dealership_id, issued_by_staff_user_id)
    references staff_user(dealership_id, id),
  constraint fk_service_invoice_canceller_same_dealership
    foreign key (dealership_id, cancelled_by_staff_user_id)
    references staff_user(dealership_id, id),
  check (invoice_total = parts_subtotal + labour_subtotal + other_subtotal - discount_amount),
  check (
    (status = 'DRAFT' and issued_at is null and issued_by_staff_user_id is null and cancelled_at is null)
    or (status = 'ISSUED' and issued_at is not null and issued_by_staff_user_id is not null and cancelled_at is null)
    or (status = 'CANCELLED' and cancelled_at is not null and cancelled_by_staff_user_id is not null)
  )
);
create unique index uq_service_invoice_active_job_card
  on service_invoice (dealership_id, job_card_id)
  where status in ('DRAFT', 'ISSUED');
create index ix_service_invoice_dealership_status
  on service_invoice (dealership_id, status, created_at desc);
create index ix_service_invoice_job_history
  on service_invoice (dealership_id, job_card_id, created_at desc);

create table service_invoice_line (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  invoice_id bigint not null,
  line_number integer not null check (line_number > 0),
  source_estimate_line_number integer not null check (source_estimate_line_number > 0),
  line_type varchar(16) not null check (line_type in ('PART', 'LABOUR', 'OTHER')),
  description varchar(300) not null,
  quantity numeric(12,3) not null check (quantity > 0),
  unit_price numeric(14,2) not null check (unit_price >= 0),
  line_total numeric(14,2) not null check (line_total >= 0),
  created_at timestamptz not null default now(),
  unique (dealership_id, invoice_id, line_number),
  constraint fk_service_invoice_line_same_dealership
    foreign key (dealership_id, invoice_id)
    references service_invoice(dealership_id, id)
);

create table service_payment (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  receipt_number varchar(48) not null,
  idempotency_key varchar(120) not null,
  request_fingerprint char(64) not null,
  payment_method varchar(24) not null
    check (payment_method in ('CASH', 'UPI', 'BANK_TRANSFER', 'CARD', 'OTHER')),
  amount numeric(14,2) not null check (amount > 0),
  payment_reference varchar(160),
  note varchar(1000),
  status varchar(16) not null default 'RECORDED' check (status in ('RECORDED', 'REVERSED')),
  recorded_by_staff_user_id bigint not null,
  recorded_at timestamptz not null default now(),
  reversed_by_staff_user_id bigint,
  reversed_at timestamptz,
  created_at timestamptz not null default now(),
  unique (dealership_id, receipt_number),
  unique (dealership_id, recorded_by_staff_user_id, idempotency_key),
  unique (dealership_id, id),
  constraint fk_service_payment_recorder_same_dealership
    foreign key (dealership_id, recorded_by_staff_user_id)
    references staff_user(dealership_id, id),
  constraint fk_service_payment_reverser_same_dealership
    foreign key (dealership_id, reversed_by_staff_user_id)
    references staff_user(dealership_id, id),
  check (
    (status = 'RECORDED' and reversed_by_staff_user_id is null and reversed_at is null)
    or (status = 'REVERSED' and reversed_by_staff_user_id is not null and reversed_at is not null)
  )
);
create index ix_service_payment_dealership_recorded
  on service_payment (dealership_id, recorded_at desc);

create table service_payment_allocation (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  payment_id bigint not null,
  invoice_id bigint not null,
  amount numeric(14,2) not null check (amount > 0),
  allocated_at timestamptz not null default now(),
  allocated_by_staff_user_id bigint not null,
  unique (dealership_id, payment_id, invoice_id),
  constraint fk_service_payment_allocation_payment_same_dealership
    foreign key (dealership_id, payment_id)
    references service_payment(dealership_id, id),
  constraint fk_service_payment_allocation_invoice_same_dealership
    foreign key (dealership_id, invoice_id)
    references service_invoice(dealership_id, id),
  constraint fk_service_payment_allocation_actor_same_dealership
    foreign key (dealership_id, allocated_by_staff_user_id)
    references staff_user(dealership_id, id)
);
create index ix_service_payment_allocation_invoice
  on service_payment_allocation (dealership_id, invoice_id, allocated_at desc);

create table service_payment_reversal (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  payment_id bigint not null,
  reason varchar(500) not null,
  external_reference varchar(160),
  reversed_by_staff_user_id bigint not null,
  reversed_at timestamptz not null default now(),
  unique (dealership_id, payment_id),
  constraint fk_service_payment_reversal_payment_same_dealership
    foreign key (dealership_id, payment_id)
    references service_payment(dealership_id, id),
  constraint fk_service_payment_reversal_actor_same_dealership
    foreign key (dealership_id, reversed_by_staff_user_id)
    references staff_user(dealership_id, id)
);
