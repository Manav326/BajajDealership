-- Effective-dated, dealership-maintained on-road estimates. No rates are seeded:
-- an estimate is available only after staff enter sourced values for a model/location.
create table bajaj_location_price_profile (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id) on delete cascade,
  model_code varchar(60) not null references bajaj_catalogue_model(model_code),
  city varchar(80) not null,
  state varchar(80) not null,
  effective_from date not null,
  effective_to date,
  ex_showroom_price numeric(14,2) not null check (ex_showroom_price > 0),
  registration_fee numeric(14,2) not null default 0 check (registration_fee >= 0),
  road_tax_percent numeric(7,4) not null default 0 check (road_tax_percent >= 0 and road_tax_percent <= 100),
  insurance_fee numeric(14,2) not null default 0 check (insurance_fee >= 0),
  handling_fee numeric(14,2) not null default 0 check (handling_fee >= 0),
  other_charges numeric(14,2) not null default 0 check (other_charges >= 0),
  other_charges_label varchar(120),
  source_url text not null,
  price_note varchar(500),
  created_by_staff_user_id bigint not null,
  updated_by_staff_user_id bigint not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (effective_to is null or effective_to >= effective_from),
  check (other_charges = 0 or nullif(trim(other_charges_label), '') is not null),
  constraint fk_bajaj_location_price_dealership_model
    foreign key (dealership_id, model_code)
    references bajaj_catalogue_dealership_model(dealership_id, model_code),
  constraint fk_bajaj_location_price_creator
    foreign key (dealership_id, created_by_staff_user_id)
    references staff_user(dealership_id, id),
  constraint fk_bajaj_location_price_updater
    foreign key (dealership_id, updated_by_staff_user_id)
    references staff_user(dealership_id, id)
);
create unique index uq_bajaj_location_price_start
  on bajaj_location_price_profile(dealership_id, lower(city), lower(state), model_code, effective_from);
create index ix_bajaj_location_price_lookup
  on bajaj_location_price_profile(dealership_id, lower(city), lower(state), model_code, effective_from desc, effective_to);
