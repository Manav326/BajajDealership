-- Customer portal accounts are linked to an existing CRM customer by a single-use staff-issued invitation.
-- No account is created by matching a public phone number or email address alone.
create table customer_portal_account (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  customer_id bigint not null,
  password_hash varchar(255) not null,
  status varchar(16) not null default 'ACTIVE' check (status in ('ACTIVE', 'DISABLED')),
  failed_login_count integer not null default 0 check (failed_login_count between 0 and 1000),
  locked_until timestamptz,
  last_login_at timestamptz,
  password_changed_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, customer_id),
  unique (dealership_id, id),
  constraint fk_customer_portal_account_customer_same_dealership
    foreign key (dealership_id, customer_id) references customer(dealership_id, id)
);
create index ix_customer_portal_account_status
  on customer_portal_account (dealership_id, status, customer_id);

create table customer_portal_invitation (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  customer_id bigint not null,
  purpose varchar(16) not null check (purpose in ('SETUP', 'PASSWORD_RESET')),
  token_hash char(64) not null unique,
  issued_by_staff_user_id bigint not null,
  expires_at timestamptz not null,
  used_at timestamptz,
  revoked_at timestamptz,
  created_at timestamptz not null default now(),
  unique (dealership_id, id),
  constraint fk_customer_portal_invitation_customer_same_dealership
    foreign key (dealership_id, customer_id) references customer(dealership_id, id),
  constraint fk_customer_portal_invitation_issuer_same_dealership
    foreign key (dealership_id, issued_by_staff_user_id) references staff_user(dealership_id, id),
  check (expires_at > created_at),
  check (used_at is null or revoked_at is null)
);
create unique index uq_customer_portal_pending_invitation
  on customer_portal_invitation (dealership_id, customer_id)
  where used_at is null and revoked_at is null;
create index ix_customer_portal_invitation_expiry
  on customer_portal_invitation (expires_at)
  where used_at is null and revoked_at is null;

create table customer_portal_session (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  account_id bigint not null,
  token_hash char(64) not null unique,
  issued_at timestamptz not null default now(),
  expires_at timestamptz not null,
  last_seen_at timestamptz not null default now(),
  revoked_at timestamptz,
  user_agent varchar(300),
  remote_address_hash char(64),
  unique (dealership_id, id),
  constraint fk_customer_portal_session_account_same_dealership
    foreign key (dealership_id, account_id) references customer_portal_account(dealership_id, id),
  check (expires_at > issued_at)
);
create index ix_customer_portal_session_account
  on customer_portal_session (dealership_id, account_id, expires_at desc)
  where revoked_at is null;

create table customer_portal_activity (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  account_id bigint not null,
  action varchar(48) not null,
  entity_type varchar(48) not null,
  entity_public_id uuid,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint fk_customer_portal_activity_account_same_dealership
    foreign key (dealership_id, account_id) references customer_portal_account(dealership_id, id)
);
create index ix_customer_portal_activity_account
  on customer_portal_activity (dealership_id, account_id, created_at desc);
