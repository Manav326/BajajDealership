-- Tax-document readiness configuration. Never generates or claims a statutory invoice by itself.
create table dealership_tax_profile (
  dealership_id bigint primary key references dealership(id),
  registration_type varchar(24) not null
    check (registration_type in ('REGULAR','COMPOSITION','SEZ','UNREGISTERED')),
  gstin varchar(15),
  legal_name varchar(160),
  trade_name varchar(160),
  registered_address varchar(1000),
  state_code char(2),
  e_invoice_applicability varchar(24) not null default 'NOT_ASSESSED'
    check (e_invoice_applicability in ('NOT_ASSESSED','APPLICABLE','NOT_APPLICABLE')),
  assessed_financial_year varchar(9),
  applicability_assessment_note varchar(500),
  applicability_assessed_by_staff_user_id bigint,
  applicability_assessed_at timestamptz,
  updated_by_staff_user_id bigint not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint fk_dealership_tax_profile_updater_same_dealership
    foreign key (dealership_id, updated_by_staff_user_id) references staff_user(dealership_id, id),
  constraint fk_dealership_tax_profile_assessor_same_dealership
    foreign key (dealership_id, applicability_assessed_by_staff_user_id) references staff_user(dealership_id, id),
  check (state_code is null or state_code ~ '^[0-9]{2}$'),
  check (gstin is null or gstin ~ '^[0-9A-Z]{15}$'),
  check (
    (e_invoice_applicability = 'NOT_ASSESSED'
      and assessed_financial_year is null
      and applicability_assessment_note is null
      and applicability_assessed_by_staff_user_id is null
      and applicability_assessed_at is null)
    or
    (e_invoice_applicability in ('APPLICABLE','NOT_APPLICABLE')
      and assessed_financial_year is not null
      and applicability_assessment_note is not null
      and applicability_assessed_by_staff_user_id is not null
      and applicability_assessed_at is not null)
  ),
  check (
    (registration_type = 'UNREGISTERED' and gstin is null)
    or
    (registration_type <> 'UNREGISTERED' and gstin is not null and legal_name is not null
      and registered_address is not null and state_code is not null)
  )
);

create table dealership_tax_code (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  code varchar(48) not null,
  description varchar(250) not null,
  hsn_sac_code varchar(20) not null,
  supply_type varchar(12) not null check (supply_type in ('GOODS','SERVICES')),
  gst_rate numeric(5,2) not null check (gst_rate between 0 and 100),
  cess_rate numeric(5,2) not null default 0 check (cess_rate between 0 and 100),
  effective_from date not null,
  effective_to date,
  source_reference varchar(500),
  verification_note varchar(500),
  status varchar(16) not null default 'DRAFT' check (status in ('DRAFT','VERIFIED')),
  created_by_staff_user_id bigint not null,
  verified_by_staff_user_id bigint,
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, code),
  unique (dealership_id, id),
  constraint fk_dealership_tax_code_creator_same_dealership
    foreign key (dealership_id, created_by_staff_user_id) references staff_user(dealership_id, id),
  constraint fk_dealership_tax_code_verifier_same_dealership
    foreign key (dealership_id, verified_by_staff_user_id) references staff_user(dealership_id, id),
  check (effective_to is null or effective_to >= effective_from),
  check (
    (status = 'DRAFT' and verified_by_staff_user_id is null and verified_at is null and verification_note is null)
    or
    (status = 'VERIFIED' and verified_by_staff_user_id is not null and verified_at is not null
      and verification_note is not null and source_reference is not null)
  )
);
create index ix_dealership_tax_code_effective
  on dealership_tax_code (dealership_id, status, effective_from, effective_to);
