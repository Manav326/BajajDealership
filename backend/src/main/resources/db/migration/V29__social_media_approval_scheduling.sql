-- Durable approval and scheduling lifecycle for external social publishing.
create table social_media_publish_request (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  destination_id bigint not null,
  asset_id bigint not null,
  created_by_staff_user_id bigint not null,
  caption varchar(2200) not null default '',
  idempotency_key varchar(120) not null,
  request_fingerprint char(64) not null,
  scheduled_at timestamptz,
  status varchar(24) not null default 'PENDING_APPROVAL'
    check(status in ('PENDING_APPROVAL','SCHEDULED','DISPATCHING','DISPATCHED','FAILED','UNKNOWN','REJECTED','CANCELLED')),
  approved_by_staff_user_id bigint,
  approved_at timestamptz,
  dispatch_lock_until timestamptz,
  publish_job_public_id uuid,
  error_code varchar(120),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  dispatched_at timestamptz,
  constraint uq_social_publish_request_id_dealership unique(id,dealership_id),
  constraint uq_social_publish_request_idempotency unique(dealership_id,idempotency_key),
  constraint fk_social_publish_request_destination_same_dealership
    foreign key(destination_id,dealership_id) references social_media_destination(id,dealership_id),
  constraint fk_social_publish_request_asset_same_dealership
    foreign key(asset_id,dealership_id) references social_media_asset(id,dealership_id),
  constraint fk_social_publish_request_creator_same_dealership
    foreign key(dealership_id,created_by_staff_user_id) references staff_user(dealership_id,id),
  constraint fk_social_publish_request_approver_same_dealership
    foreign key(dealership_id,approved_by_staff_user_id) references staff_user(dealership_id,id),
  constraint ck_social_publish_request_approval
    check ((approved_at is null and approved_by_staff_user_id is null)
      or (approved_at is not null and approved_by_staff_user_id is not null))
);
create index ix_social_publish_request_dispatch
  on social_media_publish_request(status,scheduled_at,dispatch_lock_until)
  where status in ('SCHEDULED','DISPATCHING');
create index ix_social_publish_request_history
  on social_media_publish_request(dealership_id,created_at desc);

create table social_media_publish_approval_event (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  request_id bigint not null,
  actor_staff_user_id bigint,
  action varchar(32) not null check(action in
    ('REQUESTED','APPROVED','REJECTED','CANCELLED','DISPATCHED','FAILED','UNKNOWN','RECOVERED')),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint fk_social_publish_approval_request_same_dealership
    foreign key(request_id,dealership_id) references social_media_publish_request(id,dealership_id),
  constraint fk_social_publish_approval_actor_same_dealership
    foreign key(dealership_id,actor_staff_user_id) references staff_user(dealership_id,id)
);
create index ix_social_publish_approval_history
  on social_media_publish_approval_event(dealership_id,request_id,created_at);

-- Persist future WhatsApp sends separately from provider delivery rows. The actual send row
-- is created by the existing consent/template validation path only when the worker dispatches.
create table whatsapp_scheduled_send (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  customer_id bigint not null,
  created_by_staff_user_id bigint not null,
  template_name varchar(120) not null,
  language_code varchar(32) not null,
  template_category varchar(32),
  body_parameters jsonb not null default '[]'::jsonb check(jsonb_typeof(body_parameters)='array'),
  asset_id bigint,
  idempotency_key varchar(120) not null,
  request_fingerprint char(64) not null,
  scheduled_at timestamptz not null,
  status varchar(24) not null default 'SCHEDULED'
    check(status in ('SCHEDULED','DISPATCHING','DISPATCHED','FAILED','UNKNOWN','CANCELLED')),
  dispatch_lock_until timestamptz,
  attempt_count integer not null default 0 check(attempt_count >= 0),
  next_attempt_at timestamptz not null default now(),
  message_send_id bigint,
  error_code varchar(120),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  dispatched_at timestamptz,
  constraint uq_whatsapp_scheduled_id_dealership unique(id,dealership_id),
  constraint uq_whatsapp_scheduled_idempotency unique(dealership_id,idempotency_key),
  constraint fk_whatsapp_scheduled_customer_same_dealership
    foreign key(dealership_id,customer_id) references customer(dealership_id,id),
  constraint fk_whatsapp_scheduled_creator_same_dealership
    foreign key(dealership_id,created_by_staff_user_id) references staff_user(dealership_id,id),
  constraint fk_whatsapp_scheduled_asset_same_dealership
    foreign key(asset_id,dealership_id) references social_media_asset(id,dealership_id),
  constraint fk_whatsapp_scheduled_message_same_dealership
    foreign key(message_send_id,dealership_id) references whatsapp_message_send(id,dealership_id)
);
create index ix_whatsapp_scheduled_dispatch
  on whatsapp_scheduled_send(status,scheduled_at,dispatch_lock_until)
  where status in ('SCHEDULED','DISPATCHING');
create index ix_whatsapp_scheduled_history
  on whatsapp_scheduled_send(dealership_id,created_at desc);