create table retail_part_order_collection (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null,
  order_id bigint not null,
  receipt_number varchar(48) not null,
  idempotency_key varchar(120) not null,
  request_fingerprint char(64) not null,
  collection_method varchar(24) not null check (collection_method in ('CASH', 'UPI', 'BANK_TRANSFER', 'CARD', 'OTHER')),
  amount numeric(14,2) not null check (amount > 0),
  external_reference varchar(160),
  recorded_by_staff_user_id bigint not null,
  recorded_at timestamptz not null default now(),
  unique (dealership_id, receipt_number),
  unique (dealership_id, idempotency_key),
  unique (dealership_id, id),
  foreign key (dealership_id, order_id) references retail_part_order(dealership_id, id),
  foreign key (dealership_id, recorded_by_staff_user_id) references staff_user(dealership_id, id)
);
create index ix_retail_order_collection_history
  on retail_part_order_collection(dealership_id, order_id, recorded_at desc);
