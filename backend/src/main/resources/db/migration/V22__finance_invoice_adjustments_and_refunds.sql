-- Operational credit adjustments and manually attested refund payouts.
-- This ledger never mutates issued invoices or receipt rows and is not a statutory GST credit note.
create table finance_invoice_adjustment (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  adjustment_number varchar(48) not null,
  adjustment_type varchar(20) not null check (adjustment_type in ('CREDIT_NOTE', 'REFUND')),
  source_type varchar(16) not null check (source_type in ('SALES', 'WORKSHOP')),
  sales_invoice_id bigint,
  service_invoice_id bigint,
  parent_adjustment_id bigint,
  sales_payment_id bigint,
  service_payment_id bigint,
  idempotency_key varchar(120) not null,
  request_fingerprint char(64) not null,
  amount numeric(14,2) not null check (amount > 0),
  reason varchar(500) not null,
  status varchar(24) not null default 'PENDING_APPROVAL'
    check (status in ('PENDING_APPROVAL', 'APPROVED', 'REJECTED', 'PAID')),
  created_by_staff_user_id bigint not null,
  reviewed_by_staff_user_id bigint,
  reviewed_at timestamptz,
  review_reason varchar(500),
  paid_by_staff_user_id bigint,
  paid_at timestamptz,
  payment_method varchar(24) check (payment_method is null or payment_method in ('CASH', 'UPI', 'BANK_TRANSFER', 'CARD', 'OTHER')),
  payment_reference varchar(160),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, adjustment_number),
  unique (dealership_id, id),
  unique (dealership_id, idempotency_key),
  constraint fk_finance_adjustment_sales_invoice_same_dealership
    foreign key (dealership_id, sales_invoice_id) references vehicle_sale_invoice(dealership_id, id),
  constraint fk_finance_adjustment_service_invoice_same_dealership
    foreign key (dealership_id, service_invoice_id) references service_invoice(dealership_id, id),
  constraint fk_finance_adjustment_parent_same_dealership
    foreign key (dealership_id, parent_adjustment_id) references finance_invoice_adjustment(dealership_id, id),
  constraint fk_finance_adjustment_sales_payment_same_dealership
    foreign key (dealership_id, sales_payment_id) references vehicle_sale_payment(dealership_id, id),
  constraint fk_finance_adjustment_service_payment_same_dealership
    foreign key (dealership_id, service_payment_id) references service_payment(dealership_id, id),
  constraint fk_finance_adjustment_creator_same_dealership
    foreign key (dealership_id, created_by_staff_user_id) references staff_user(dealership_id, id),
  constraint fk_finance_adjustment_reviewer_same_dealership
    foreign key (dealership_id, reviewed_by_staff_user_id) references staff_user(dealership_id, id),
  constraint fk_finance_adjustment_payer_same_dealership
    foreign key (dealership_id, paid_by_staff_user_id) references staff_user(dealership_id, id),
  check (
    (source_type = 'SALES' and sales_invoice_id is not null and service_invoice_id is null)
    or (source_type = 'WORKSHOP' and service_invoice_id is not null and sales_invoice_id is null)
  ),
  check (
    (adjustment_type = 'CREDIT_NOTE' and parent_adjustment_id is null
      and sales_payment_id is null and service_payment_id is null
      and paid_by_staff_user_id is null and paid_at is null
      and payment_method is null and payment_reference is null)
    or (adjustment_type = 'REFUND' and parent_adjustment_id is not null
      and ((source_type = 'SALES' and sales_payment_id is not null and service_payment_id is null)
        or (source_type = 'WORKSHOP' and service_payment_id is not null and sales_payment_id is null)))
  ),
  check (
    (status = 'PENDING_APPROVAL' and reviewed_by_staff_user_id is null and reviewed_at is null
      and review_reason is null and paid_by_staff_user_id is null and paid_at is null
      and payment_method is null and payment_reference is null)
    or (status = 'APPROVED' and reviewed_by_staff_user_id is not null and reviewed_at is not null
      and review_reason is null and paid_by_staff_user_id is null and paid_at is null
      and payment_method is null and payment_reference is null)
    or (status = 'REJECTED' and reviewed_by_staff_user_id is not null and reviewed_at is not null
      and review_reason is not null and paid_by_staff_user_id is null and paid_at is null
      and payment_method is null and payment_reference is null)
    or (status = 'PAID' and adjustment_type = 'REFUND'
      and reviewed_by_staff_user_id is not null and reviewed_at is not null
      and review_reason is null and paid_by_staff_user_id is not null and paid_at is not null
      and payment_method is not null
      and (payment_method not in ('UPI', 'BANK_TRANSFER', 'CARD') or nullif(trim(payment_reference), '') is not null))
  )
);
create index ix_finance_adjustment_invoice_history
  on finance_invoice_adjustment (dealership_id, source_type, sales_invoice_id, service_invoice_id, created_at desc);
create index ix_finance_adjustment_review_queue
  on finance_invoice_adjustment (dealership_id, status, created_at asc);
create index ix_finance_adjustment_parent_refunds
  on finance_invoice_adjustment (dealership_id, parent_adjustment_id, status);
create index ix_finance_adjustment_paid_channel
  on finance_invoice_adjustment (dealership_id, paid_at, payment_method)
  where adjustment_type = 'REFUND' and status = 'PAID';

create table finance_invoice_adjustment_event (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  adjustment_id bigint not null,
  event_type varchar(16) not null check (event_type in ('CREATED', 'APPROVED', 'REJECTED', 'PAID')),
  from_status varchar(24),
  to_status varchar(24) not null check (to_status in ('PENDING_APPROVAL', 'APPROVED', 'REJECTED', 'PAID')),
  reason varchar(500) not null,
  external_reference varchar(160),
  actor_staff_user_id bigint not null,
  created_at timestamptz not null default now(),
  constraint fk_finance_adjustment_event_adjustment_same_dealership
    foreign key (dealership_id, adjustment_id) references finance_invoice_adjustment(dealership_id, id),
  constraint fk_finance_adjustment_event_actor_same_dealership
    foreign key (dealership_id, actor_staff_user_id) references staff_user(dealership_id, id)
);
create index ix_finance_adjustment_event_history
  on finance_invoice_adjustment_event (dealership_id, adjustment_id, created_at, id);

-- History is append-only even if a caller accidentally attempts a mutation.
create function prevent_finance_adjustment_event_mutation() returns trigger
language plpgsql as $$
begin
  raise exception 'finance adjustment history is append-only';
end;
$$;
create trigger trg_finance_adjustment_event_append_only
  before update or delete on finance_invoice_adjustment_event
  for each row execute function prevent_finance_adjustment_event_mutation();

alter table daily_finance_close_channel
  add column refund_payouts numeric(16,2) not null default 0 check (refund_payouts >= 0);

insert into permission(code, description)
values ('finance.adjustment.approve', 'Review and approve or reject financial credit adjustments and refund requests')
on conflict (code) do nothing;
insert into role_permission(role_id, permission_id)
select r.id, p.id from role r join permission p on p.code = 'finance.adjustment.approve'
where r.code in ('OWNER', 'MANAGER')
on conflict do nothing;
