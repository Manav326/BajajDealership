create table customer_whatsapp_consent(
 id bigint generated by default as identity primary key,
 public_id uuid not null default gen_random_uuid() unique,
 dealership_id bigint not null references dealership(id),
 customer_id bigint not null,
 phone_number_e164 varchar(16) not null check(phone_number_e164 ~ '^\+[1-9][0-9]{7,14}$'),
 status varchar(16) not null check(status in('OPTED_IN','OPTED_OUT')),
 consent_source varchar(100) not null,
 evidence_reference varchar(500),
 captured_by_staff_user_id bigint,
 consented_at timestamptz,
 opted_out_at timestamptz,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 constraint uq_customer_whatsapp_consent unique(dealership_id,customer_id),
 constraint fk_whatsapp_consent_customer_same_dealership foreign key(dealership_id,customer_id) references customer(dealership_id,id),
 constraint fk_whatsapp_consent_actor_same_dealership foreign key(dealership_id,captured_by_staff_user_id) references staff_user(dealership_id,id),
 check((status='OPTED_IN' and consented_at is not null and opted_out_at is null) or (status='OPTED_OUT' and opted_out_at is not null))
);
create index ix_customer_whatsapp_consent_status on customer_whatsapp_consent(dealership_id,status,updated_at desc);

create table whatsapp_message_send(
 id bigint generated by default as identity primary key,
 public_id uuid not null default gen_random_uuid() unique,
 dealership_id bigint not null references dealership(id),
 customer_id bigint not null,
 created_by_staff_user_id bigint not null,
 template_name varchar(120) not null,
 language_code varchar(32) not null,
 template_category varchar(32),
 body_parameters jsonb not null default '[]'::jsonb check(jsonb_typeof(body_parameters)='array'),
 asset_id bigint,
 idempotency_key varchar(120) not null,
 request_fingerprint char(64) not null,
 status varchar(16) not null default 'PROCESSING' check(status in('PROCESSING','ACCEPTED','SENT','DELIVERED','READ','FAILED','UNKNOWN')),
 provider_message_id varchar(200) unique,
 error_code varchar(120),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 accepted_at timestamptz,
 sent_at timestamptz,
 delivered_at timestamptz,
 read_at timestamptz,
 failed_at timestamptz,
 constraint uq_whatsapp_message_id_dealership unique(id,dealership_id),
 constraint uq_whatsapp_message_idempotency unique(dealership_id,idempotency_key),
 constraint fk_whatsapp_message_customer_same_dealership foreign key(dealership_id,customer_id) references customer(dealership_id,id),
 constraint fk_whatsapp_message_actor_same_dealership foreign key(dealership_id,created_by_staff_user_id) references staff_user(dealership_id,id),
 constraint fk_whatsapp_message_asset_same_dealership foreign key(asset_id,dealership_id) references social_media_asset(id,dealership_id)
);
create index ix_whatsapp_message_history on whatsapp_message_send(dealership_id,created_at desc);
create index ix_whatsapp_message_customer_history on whatsapp_message_send(dealership_id,customer_id,created_at desc);

create table whatsapp_audit_event(
 id bigint generated by default as identity primary key,
 dealership_id bigint not null references dealership(id),
 actor_staff_user_id bigint,
 action varchar(100) not null,
 details jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now(),
 constraint fk_whatsapp_audit_actor_same_dealership foreign key(dealership_id,actor_staff_user_id) references staff_user(dealership_id,id)
);
create index ix_whatsapp_audit_history on whatsapp_audit_event(dealership_id,created_at desc);
