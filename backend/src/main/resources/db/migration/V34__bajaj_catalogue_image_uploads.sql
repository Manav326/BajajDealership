-- Optional dealership-owned image gallery. Existing official Bajaj CDN images remain the seeded fallback.
-- Uploaded files are raster-only and bounded by the API to 4.5 MiB.
create table bajaj_catalogue_image (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id) on delete cascade,
  model_code varchar(60) not null references bajaj_catalogue_model(model_code),
  original_filename varchar(180) not null,
  content_type varchar(32) not null check (content_type in ('image/jpeg','image/png','image/webp')),
  image_bytes bytea not null,
  sha256 char(64) not null,
  size_bytes integer not null check (size_bytes between 1 and 4718592),
  sort_order integer not null default 100,
  is_primary boolean not null default false,
  uploaded_by_staff_user_id bigint not null,
  created_at timestamptz not null default now(),
  constraint uq_bajaj_catalogue_image_dealership_id unique (dealership_id, id),
  constraint fk_bajaj_catalogue_image_staff_same_dealership
    foreign key (dealership_id, uploaded_by_staff_user_id) references staff_user(dealership_id, id)
);
create index ix_bajaj_catalogue_image_gallery
  on bajaj_catalogue_image(dealership_id, model_code, is_primary desc, sort_order, id desc);
create unique index uq_bajaj_catalogue_one_primary_image
  on bajaj_catalogue_image(dealership_id, model_code) where is_primary;

