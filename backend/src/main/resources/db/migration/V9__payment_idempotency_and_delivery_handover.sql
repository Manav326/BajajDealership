-- Use dealership-wide idempotency keys so retrying from another staff session cannot duplicate receipts.
alter table service_payment
  drop constraint service_payment_dealership_id_recorded_by_staff_user_id_idempotency_key_key;
alter table service_payment
  add constraint uq_service_payment_idempotency_per_dealership
  unique (dealership_id, idempotency_key);

alter table service_invoice
  add constraint uq_service_invoice_delivery_target unique (dealership_id, id, job_card_id);

insert into permission (code, description)
values ('finance.payment.reverse', 'Reverse an operational payment record with an audited reason')
on conflict (code) do nothing;

insert into role_permission (role_id, permission_id)
select r.id, p.id
from role r join permission p on p.code = 'finance.payment.reverse'
where r.code in ('OWNER', 'MANAGER')
on conflict do nothing;

create table service_delivery_handover (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  job_card_id bigint not null,
  invoice_id bigint not null,
  customer_id bigint not null,
  delivered_to_name varchar(160) not null,
  customer_acknowledged boolean not null check (customer_acknowledged = true),
  acknowledgement_method varchar(24) not null
    check (acknowledgement_method in ('IN_PERSON', 'SIGNED_FORM', 'OTP_REFERENCE', 'WRITTEN_MESSAGE')),
  acknowledgement_reference varchar(160),
  note varchar(1000),
  delivered_by_staff_user_id bigint not null,
  delivered_at timestamptz not null default now(),
  unique (dealership_id, job_card_id),
  constraint fk_service_handover_job_card_same_dealership
    foreign key (dealership_id, job_card_id)
    references service_job_card(dealership_id, id),
  constraint fk_service_handover_invoice_for_job
    foreign key (dealership_id, invoice_id, job_card_id)
    references service_invoice(dealership_id, id, job_card_id),
  constraint fk_service_handover_customer_same_dealership
    foreign key (dealership_id, customer_id)
    references customer(dealership_id, id),
  constraint fk_service_handover_actor_same_dealership
    foreign key (dealership_id, delivered_by_staff_user_id)
    references staff_user(dealership_id, id),
  constraint ck_service_handover_ack_evidence
    check (acknowledgement_method not in ('SIGNED_FORM', 'OTP_REFERENCE')
      or nullif(trim(acknowledgement_reference), '') is not null)
);
create index ix_service_delivery_handover_history
  on service_delivery_handover (dealership_id, delivered_at desc);
