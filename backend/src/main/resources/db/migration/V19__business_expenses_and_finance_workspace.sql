-- General operating expenses with review and reversal history.
-- This ledger is separate from operational invoices and does not calculate GST.
create table business_expense (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  expense_number varchar(48) not null,
  idempotency_key varchar(120) not null,
  request_fingerprint char(64) not null,
  expense_date date not null,
  category varchar(64) not null,
  description varchar(500) not null,
  vendor_name varchar(160),
  payment_method varchar(24) not null check (payment_method in ('CASH', 'UPI', 'BANK_TRANSFER', 'CARD', 'OTHER')),
  payment_reference varchar(160),
  amount numeric(14,2) not null check (amount > 0),
  status varchar(24) not null default 'PENDING_APPROVAL'
    check (status in ('PENDING_APPROVAL', 'APPROVED', 'REJECTED', 'REVERSED')),
  created_by_staff_user_id bigint not null,
  reviewed_by_staff_user_id bigint,
  reviewed_at timestamptz,
  review_reason varchar(500),
  reversed_by_staff_user_id bigint,
  reversed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, expense_number),
  unique (dealership_id, id),
  unique (dealership_id, idempotency_key),
  constraint fk_business_expense_creator_same_dealership
    foreign key (dealership_id, created_by_staff_user_id) references staff_user(dealership_id, id),
  constraint fk_business_expense_reviewer_same_dealership
    foreign key (dealership_id, reviewed_by_staff_user_id) references staff_user(dealership_id, id),
  constraint fk_business_expense_reverser_same_dealership
    foreign key (dealership_id, reversed_by_staff_user_id) references staff_user(dealership_id, id),
  check (
    (status = 'PENDING_APPROVAL' and reviewed_by_staff_user_id is null and reviewed_at is null
      and review_reason is null and reversed_by_staff_user_id is null and reversed_at is null)
    or
    (status = 'APPROVED' and reviewed_by_staff_user_id is not null and reviewed_at is not null
      and review_reason is null and reversed_by_staff_user_id is null and reversed_at is null)
    or
    (status = 'REJECTED' and reviewed_by_staff_user_id is not null and reviewed_at is not null
      and review_reason is not null and reversed_by_staff_user_id is null and reversed_at is null)
    or
    (status = 'REVERSED' and reviewed_by_staff_user_id is not null and reviewed_at is not null
      and reversed_by_staff_user_id is not null and reversed_at is not null)
  )
);
create index ix_business_expense_dealership_date
  on business_expense (dealership_id, expense_date desc, created_at desc);
create index ix_business_expense_review_queue
  on business_expense (dealership_id, status, created_at asc);

create table business_expense_reversal (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  expense_id bigint not null,
  reason varchar(500) not null,
  external_reference varchar(160),
  reversed_by_staff_user_id bigint not null,
  reversed_at timestamptz not null default now(),
  unique (dealership_id, expense_id),
  constraint fk_business_expense_reversal_expense_same_dealership
    foreign key (dealership_id, expense_id) references business_expense(dealership_id, id),
  constraint fk_business_expense_reversal_actor_same_dealership
    foreign key (dealership_id, reversed_by_staff_user_id) references staff_user(dealership_id, id)
);
create index ix_business_expense_reversal_history
  on business_expense_reversal (dealership_id, reversed_at desc);

insert into permission (code, description)
values ('finance.expense.reverse', 'Reverse an approved expense with a reason and audit history')
on conflict (code) do nothing;

insert into role_permission (role_id, permission_id)
select r.id, p.id from role r join permission p on p.code = 'finance.expense.reverse'
where r.code in ('OWNER', 'MANAGER')
on conflict do nothing;
