-- Customer-facing sales requests and retail spare-parts orders.
-- These are requests/orders, not fabricated unit reservations, quotes or payment-provider successes.

alter table spare_part
  add column retail_enabled boolean not null default false,
  add column retail_price numeric(14,2),
  add column retail_description varchar(1000),
  add column fitment_model_codes jsonb not null default '[]'::jsonb
    check (jsonb_typeof(fitment_model_codes) = 'array'),
  add column retail_image_url text,
  add column retail_updated_by_staff_user_id bigint,
  add constraint fk_spare_part_retail_updater_same_dealership
    foreign key (dealership_id, retail_updated_by_staff_user_id)
    references staff_user(dealership_id, id),
  add constraint ck_spare_part_retail_price
    check (retail_price is null or retail_price > 0),
  add constraint ck_spare_part_retail_enabled_price
    check (not retail_enabled or retail_price is not null);

alter table spare_part_stock_movement
  drop constraint spare_part_stock_movement_movement_type_check,
  add constraint ck_spare_part_stock_movement_type
    check (movement_type in (
      'PURCHASE_RECEIPT', 'RESERVATION_CREATED', 'RESERVATION_RELEASED',
      'ISSUED_TO_JOB', 'RETURNED_FROM_JOB', 'STOCK_CORRECTION',
      'RETAIL_ORDER_RESERVED', 'RETAIL_ORDER_RELEASED', 'RETAIL_ORDER_FULFILLED'
    )),
  alter column actor_staff_user_id drop not null,
  add column actor_customer_id bigint,
  add constraint fk_spare_part_movement_customer_same_dealership
    foreign key (dealership_id, actor_customer_id)
    references customer(dealership_id, id),
  add constraint ck_spare_part_movement_actor
    check (
      (actor_staff_user_id is not null and actor_customer_id is null)
      or (actor_staff_user_id is null and actor_customer_id is not null)
    );

create table customer_sales_request (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  request_code varchar(48) not null,
  customer_id bigint not null,
  customer_portal_account_id bigint not null,
  request_type varchar(20) not null check (request_type in ('TEST_RIDE', 'PURCHASE')),
  model_code varchar(60) not null references bajaj_catalogue_model(model_code),
  preferred_at timestamptz,
  notes varchar(1000),
  status varchar(20) not null default 'REQUESTED'
    check (status in ('REQUESTED', 'CONVERTED', 'CANCELLED')),
  converted_enquiry_id bigint,
  converted_by_staff_user_id bigint,
  converted_at timestamptz,
  cancelled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, request_code),
  unique (dealership_id, id),
  constraint fk_customer_sales_request_customer_same_dealership
    foreign key (dealership_id, customer_id) references customer(dealership_id, id),
  constraint fk_customer_sales_request_account_same_dealership
    foreign key (dealership_id, customer_portal_account_id) references customer_portal_account(dealership_id, id),
  constraint fk_customer_sales_request_converted_enquiry_same_dealership
    foreign key (dealership_id, converted_enquiry_id) references sales_enquiry(dealership_id, id),
  constraint fk_customer_sales_request_converter_same_dealership
    foreign key (dealership_id, converted_by_staff_user_id) references staff_user(dealership_id, id),
  constraint ck_customer_sales_request_conversion
    check (
      (status = 'CONVERTED' and converted_enquiry_id is not null
        and converted_by_staff_user_id is not null and converted_at is not null and cancelled_at is null)
      or (status <> 'CONVERTED' and converted_enquiry_id is null
        and converted_by_staff_user_id is null and converted_at is null)
    ),
  constraint ck_customer_sales_request_cancellation
    check ((status = 'CANCELLED' and cancelled_at is not null)
      or (status <> 'CANCELLED' and cancelled_at is null))
);
create index ix_customer_sales_request_queue
  on customer_sales_request(dealership_id, status, created_at desc);
create index ix_customer_sales_request_customer
  on customer_sales_request(dealership_id, customer_id, created_at desc);

create table retail_part_order (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  order_code varchar(48) not null,
  customer_id bigint not null,
  customer_portal_account_id bigint not null,
  idempotency_key varchar(120) not null,
  request_fingerprint char(64) not null,
  status varchar(20) not null default 'PLACED'
    check (status in ('PLACED', 'CANCELLED', 'FULFILLED')),
  payment_method varchar(24) not null default 'PAY_AT_PICKUP'
    check (payment_method = 'PAY_AT_PICKUP'),
  payment_status varchar(24) not null default 'PAY_ON_PICKUP'
    check (payment_status in ('PAY_ON_PICKUP', 'PAID_AT_PICKUP')),
  order_total numeric(16,2) not null check (order_total > 0),
  customer_note varchar(1000),
  cancelled_at timestamptz,
  fulfilled_by_staff_user_id bigint,
  fulfilled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, order_code),
  unique (dealership_id, id),
  unique (dealership_id, idempotency_key),
  constraint fk_retail_order_customer_same_dealership
    foreign key (dealership_id, customer_id) references customer(dealership_id, id),
  constraint fk_retail_order_account_same_dealership
    foreign key (dealership_id, customer_portal_account_id) references customer_portal_account(dealership_id, id),
  constraint fk_retail_order_fulfiller_same_dealership
    foreign key (dealership_id, fulfilled_by_staff_user_id) references staff_user(dealership_id, id),
  constraint ck_retail_order_cancelled
    check ((status = 'CANCELLED' and cancelled_at is not null)
      or (status <> 'CANCELLED' and cancelled_at is null)),
  constraint ck_retail_order_fulfilled
    check ((status = 'FULFILLED' and fulfilled_at is not null and fulfilled_by_staff_user_id is not null)
      or (status <> 'FULFILLED' and fulfilled_at is null and fulfilled_by_staff_user_id is null))
);
create index ix_retail_part_order_customer_history
  on retail_part_order(dealership_id, customer_id, created_at desc);
create index ix_retail_part_order_queue
  on retail_part_order(dealership_id, status, created_at desc);

create table retail_part_order_line (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  order_id bigint not null,
  part_id bigint not null,
  line_number integer not null check (line_number > 0),
  sku_code varchar(60) not null,
  part_name varchar(200) not null,
  unit_of_measure varchar(16) not null,
  quantity numeric(12,3) not null check (quantity > 0),
  unit_price numeric(14,2) not null check (unit_price > 0),
  line_total numeric(16,2) not null check (line_total > 0),
  created_at timestamptz not null default now(),
  unique (dealership_id, order_id, line_number),
  unique (dealership_id, order_id, part_id),
  constraint fk_retail_order_line_order_same_dealership
    foreign key (dealership_id, order_id) references retail_part_order(dealership_id, id),
  constraint fk_retail_order_line_part_same_dealership
    foreign key (dealership_id, part_id) references spare_part(dealership_id, id),
  check (line_total = round(quantity * unit_price, 2))
);
create index ix_retail_order_line_part_history
  on retail_part_order_line(dealership_id, part_id, created_at desc);
