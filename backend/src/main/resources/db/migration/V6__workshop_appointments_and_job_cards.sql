create table service_appointment (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  appointment_code varchar(48) not null,
  customer_id bigint not null,
  vehicle_unit_id bigint not null,
  scheduled_for timestamptz not null,
  slot_minutes integer not null default 60 check (slot_minutes between 15 and 480),
  customer_concern varchar(3000) not null,
  customer_language varchar(12) not null default 'hi'
    check (customer_language in ('hi', 'en', 'hinglish')),
  source varchar(24) not null default 'STAFF'
    check (source in ('STAFF', 'PHONE', 'WALK_IN', 'CUSTOMER_WEB', 'CUSTOMER_APP')),
  status varchar(24) not null default 'REQUESTED'
    check (status in ('REQUESTED', 'CONFIRMED', 'CANCELLED', 'CHECKED_IN', 'NO_SHOW', 'COMPLETED')),
  status_reason varchar(500),
  staff_notes varchar(3000),
  requested_by_staff_user_id bigint,
  confirmed_by_staff_user_id bigint,
  cancelled_by_staff_user_id bigint,
  checked_in_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, appointment_code),
  unique (dealership_id, id),
  constraint fk_service_appointment_customer_same_dealership
    foreign key (dealership_id, customer_id) references customer(dealership_id, id),
  constraint fk_service_appointment_vehicle_same_dealership
    foreign key (dealership_id, vehicle_unit_id) references vehicle_unit(dealership_id, id),
  constraint fk_service_appointment_requester_same_dealership
    foreign key (dealership_id, requested_by_staff_user_id) references staff_user(dealership_id, id),
  constraint fk_service_appointment_confirmer_same_dealership
    foreign key (dealership_id, confirmed_by_staff_user_id) references staff_user(dealership_id, id),
  constraint fk_service_appointment_canceller_same_dealership
    foreign key (dealership_id, cancelled_by_staff_user_id) references staff_user(dealership_id, id)
);

create table service_appointment_transition (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  appointment_id bigint not null,
  from_status varchar(24),
  to_status varchar(24) not null,
  action varchar(48) not null,
  actor_staff_user_id bigint,
  reason varchar(500),
  created_at timestamptz not null default now(),
  constraint fk_appointment_transition_appointment_same_dealership
    foreign key (dealership_id, appointment_id) references service_appointment(dealership_id, id),
  constraint fk_appointment_transition_actor_same_dealership
    foreign key (dealership_id, actor_staff_user_id) references staff_user(dealership_id, id)
);
create index ix_service_appointment_transition_history
  on service_appointment_transition (dealership_id, appointment_id, created_at desc);

create index ix_service_appointment_schedule
  on service_appointment (dealership_id, scheduled_for, id)
  where status in ('REQUESTED', 'CONFIRMED');
create index ix_service_appointment_customer_history
  on service_appointment (dealership_id, customer_id, scheduled_for desc);
create index ix_service_appointment_vehicle_history
  on service_appointment (dealership_id, vehicle_unit_id, scheduled_for desc);

create table service_job_card (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  job_card_code varchar(48) not null,
  appointment_id bigint,
  customer_id bigint not null,
  vehicle_unit_id bigint not null,
  status varchar(32) not null default 'INSPECTING'
    check (status in ('OPEN', 'INSPECTING', 'ESTIMATE_PENDING', 'AWAITING_APPROVAL',
      'APPROVED', 'IN_PROGRESS', 'QUALITY_CHECK', 'READY_FOR_COLLECTION',
      'INVOICED', 'DELIVERED', 'CANCELLED')),
  customer_concern varchar(3000) not null,
  odometer_km integer check (odometer_km is null or odometer_km >= 0),
  fuel_level_percent integer check (fuel_level_percent is null or fuel_level_percent between 0 and 100),
  checkin_notes varchar(3000),
  checked_in_by_staff_user_id bigint not null,
  checked_in_at timestamptz not null default now(),
  completed_at timestamptz,
  delivered_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, job_card_code),
  unique (dealership_id, id),
  constraint uq_service_job_card_appointment unique (dealership_id, appointment_id),
  constraint fk_job_card_appointment_same_dealership
    foreign key (dealership_id, appointment_id) references service_appointment(dealership_id, id),
  constraint fk_job_card_customer_same_dealership
    foreign key (dealership_id, customer_id) references customer(dealership_id, id),
  constraint fk_job_card_vehicle_same_dealership
    foreign key (dealership_id, vehicle_unit_id) references vehicle_unit(dealership_id, id),
  constraint fk_job_card_checkin_actor_same_dealership
    foreign key (dealership_id, checked_in_by_staff_user_id) references staff_user(dealership_id, id),
  check (completed_at is null or completed_at >= checked_in_at),
  check (delivered_at is null or completed_at is not null)
);

create index ix_service_job_card_status
  on service_job_card (dealership_id, status, checked_in_at desc);
create index ix_service_job_card_customer_history
  on service_job_card (dealership_id, customer_id, checked_in_at desc);
create index ix_service_job_card_vehicle_history
  on service_job_card (dealership_id, vehicle_unit_id, checked_in_at desc);

create table service_job_assignment (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  job_card_id bigint not null,
  assigned_staff_user_id bigint not null,
  assignment_role varchar(24) not null
    check (assignment_role in ('SERVICE_ADVISOR', 'TECHNICIAN', 'QUALITY_INSPECTOR')),
  assigned_by_staff_user_id bigint not null,
  assigned_at timestamptz not null default now(),
  unassigned_at timestamptz,
  note varchar(500),
  constraint fk_job_assignment_card_same_dealership
    foreign key (dealership_id, job_card_id) references service_job_card(dealership_id, id),
  constraint fk_job_assignment_staff_same_dealership
    foreign key (dealership_id, assigned_staff_user_id) references staff_user(dealership_id, id),
  constraint fk_job_assignment_assigner_same_dealership
    foreign key (dealership_id, assigned_by_staff_user_id) references staff_user(dealership_id, id),
  check (unassigned_at is null or unassigned_at >= assigned_at)
);
create unique index uq_service_job_current_assignment
  on service_job_assignment (dealership_id, job_card_id, assignment_role)
  where unassigned_at is null;
create index ix_service_job_assignments_staff
  on service_job_assignment (dealership_id, assigned_staff_user_id, assigned_at desc);

create table service_job_transition (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  job_card_id bigint not null,
  from_status varchar(32),
  to_status varchar(32) not null,
  action varchar(64) not null,
  actor_staff_user_id bigint,
  reason varchar(500),
  request_key varchar(120),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint fk_job_transition_card_same_dealership
    foreign key (dealership_id, job_card_id) references service_job_card(dealership_id, id),
  constraint fk_job_transition_actor_same_dealership
    foreign key (dealership_id, actor_staff_user_id) references staff_user(dealership_id, id),
  unique (dealership_id, request_key)
);
create index ix_service_job_transition_history
  on service_job_transition (dealership_id, job_card_id, created_at desc);

create table service_inspection_item (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  job_card_id bigint not null,
  checklist_code varchar(80) not null,
  label varchar(180) not null,
  status varchar(20) not null default 'PENDING'
    check (status in ('PENDING', 'OK', 'ATTENTION', 'NOT_APPLICABLE')),
  notes varchar(1000),
  checked_by_staff_user_id bigint,
  checked_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, job_card_id, checklist_code),
  constraint fk_service_inspection_job_same_dealership
    foreign key (dealership_id, job_card_id) references service_job_card(dealership_id, id),
  constraint fk_service_inspection_actor_same_dealership
    foreign key (dealership_id, checked_by_staff_user_id) references staff_user(dealership_id, id),
  check ((status = 'PENDING' and checked_at is null) or (status <> 'PENDING' and checked_at is not null))
);

create table service_estimate (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  job_card_id bigint not null,
  revision integer not null check (revision > 0),
  status varchar(28) not null default 'DRAFT'
    check (status in ('DRAFT', 'AWAITING_CUSTOMER', 'APPROVED', 'DECLINED', 'SUPERSEDED')),
  parts_subtotal numeric(14,2) not null default 0 check (parts_subtotal >= 0),
  labour_subtotal numeric(14,2) not null default 0 check (labour_subtotal >= 0),
  other_subtotal numeric(14,2) not null default 0 check (other_subtotal >= 0),
  discount_amount numeric(14,2) not null default 0 check (discount_amount >= 0),
  estimated_total numeric(14,2) not null default 0 check (estimated_total >= 0),
  customer_message varchar(2000),
  created_by_staff_user_id bigint not null,
  submitted_at timestamptz,
  decided_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dealership_id, job_card_id, revision),
  unique (dealership_id, id),
  constraint fk_service_estimate_job_same_dealership
    foreign key (dealership_id, job_card_id) references service_job_card(dealership_id, id),
  constraint fk_service_estimate_creator_same_dealership
    foreign key (dealership_id, created_by_staff_user_id) references staff_user(dealership_id, id)
);
create index ix_service_estimate_job_revision
  on service_estimate (dealership_id, job_card_id, revision desc);

create table service_estimate_line (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  estimate_id bigint not null,
  line_number integer not null check (line_number > 0),
  line_type varchar(16) not null check (line_type in ('PART', 'LABOUR', 'OTHER')),
  description varchar(300) not null,
  quantity numeric(12,3) not null default 1 check (quantity > 0),
  unit_price numeric(14,2) not null check (unit_price >= 0),
  line_total numeric(14,2) not null check (line_total >= 0),
  created_at timestamptz not null default now(),
  unique (dealership_id, estimate_id, line_number),
  constraint fk_service_estimate_line_same_dealership
    foreign key (dealership_id, estimate_id) references service_estimate(dealership_id, id)
);

create table service_estimate_decision (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  estimate_id bigint not null,
  decision varchar(24) not null check (decision in ('APPROVED', 'DECLINED', 'REVISION_REQUESTED')),
  evidence_method varchar(24) not null
    check (evidence_method in ('OTP', 'SIGNED_FORM', 'IN_PERSON', 'PHONE_RECORD', 'WRITTEN_MESSAGE')),
  evidence_reference varchar(160),
  note varchar(1000),
  recorded_by_staff_user_id bigint not null,
  recorded_at timestamptz not null default now(),
  constraint fk_service_estimate_decision_same_dealership
    foreign key (dealership_id, estimate_id) references service_estimate(dealership_id, id),
  constraint fk_service_estimate_decision_actor_same_dealership
    foreign key (dealership_id, recorded_by_staff_user_id) references staff_user(dealership_id, id)
);
create index ix_service_estimate_decision_history
  on service_estimate_decision (dealership_id, estimate_id, recorded_at desc);

