-- Optional dealership-authored promotions. No promotional offers are seeded or implied.
create table bajaj_showroom_promotion (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id) on delete cascade,
  model_code varchar(60),
  title varchar(120) not null,
  summary varchar(400) not null,
  terms varchar(2000),
  starts_on date not null,
  ends_on date,
  source_url text not null,
  is_published boolean not null default false,
  created_by_staff_user_id bigint not null,
  updated_by_staff_user_id bigint not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_on is null or ends_on >= starts_on),
  constraint fk_bajaj_showroom_promotion_model_same_dealership
    foreign key (dealership_id, model_code)
    references bajaj_catalogue_dealership_model(dealership_id, model_code),
  constraint fk_bajaj_showroom_promotion_creator
    foreign key (dealership_id, created_by_staff_user_id)
    references staff_user(dealership_id, id),
  constraint fk_bajaj_showroom_promotion_updater
    foreign key (dealership_id, updated_by_staff_user_id)
    references staff_user(dealership_id, id)
);
create index ix_bajaj_showroom_promotion_public
  on bajaj_showroom_promotion(dealership_id, is_published, starts_on, ends_on);
create index ix_bajaj_showroom_promotion_model
  on bajaj_showroom_promotion(dealership_id, model_code, starts_on, ends_on);
