-- Full-order retail returns are separate from pickup collections. No automatic refund is initiated.
alter table spare_part_stock_movement
  drop constraint ck_spare_part_stock_movement_type,
  add constraint ck_spare_part_stock_movement_type
    check (movement_type in (
      'PURCHASE_RECEIPT', 'RESERVATION_CREATED', 'RESERVATION_RELEASED',
      'ISSUED_TO_JOB', 'RETURNED_FROM_JOB', 'STOCK_CORRECTION',
      'RETAIL_ORDER_RESERVED', 'RETAIL_ORDER_RELEASED', 'RETAIL_ORDER_FULFILLED',
      'RETAIL_ORDER_RETURNED'
    ));

alter table retail_part_order
  drop constraint retail_part_order_status_check,
  add constraint ck_retail_part_order_status
    check (status in ('PLACED', 'CANCELLED', 'FULFILLED', 'RETURNED')),
  drop constraint retail_part_order_payment_status_check,
  add constraint ck_retail_part_order_payment_status
    check (payment_status in ('PAY_ON_PICKUP', 'PAID_AT_PICKUP', 'REFUND_REVIEW_REQUIRED')),
  drop constraint ck_retail_order_fulfilled,
  add column returned_by_staff_user_id bigint,
  add column returned_at timestamptz,
  add column returned_reason varchar(1000),
  add column returned_restocked boolean,
  add constraint fk_retail_order_return_staff_same_dealership
    foreign key (dealership_id, returned_by_staff_user_id) references staff_user(dealership_id, id),
  add constraint ck_retail_order_fulfilled
    check (
      (status in ('FULFILLED', 'RETURNED') and fulfilled_at is not null and fulfilled_by_staff_user_id is not null)
      or (status not in ('FULFILLED', 'RETURNED') and fulfilled_at is null and fulfilled_by_staff_user_id is null)
    ),
  add constraint ck_retail_order_returned
    check (
      (status = 'RETURNED' and returned_at is not null and returned_by_staff_user_id is not null
        and returned_reason is not null and returned_restocked is not null
        and payment_status = 'REFUND_REVIEW_REQUIRED')
      or (status <> 'RETURNED' and returned_at is null and returned_by_staff_user_id is null
        and returned_reason is null and returned_restocked is null
        and payment_status <> 'REFUND_REVIEW_REQUIRED')
    );

create table retail_part_order_return (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null,
  order_id bigint not null,
  return_code varchar(48) not null,
  idempotency_key varchar(120) not null,
  request_fingerprint char(64) not null,
  reason varchar(1000) not null,
  restocked boolean not null,
  amount_review_required numeric(16,2) not null check (amount_review_required > 0),
  recorded_by_staff_user_id bigint not null,
  returned_at timestamptz not null default now(),
  unique (dealership_id, return_code),
  unique (dealership_id, idempotency_key),
  unique (dealership_id, order_id),
  foreign key (dealership_id, order_id) references retail_part_order(dealership_id, id),
  foreign key (dealership_id, recorded_by_staff_user_id) references staff_user(dealership_id, id)
);
create index ix_retail_part_order_return_history
  on retail_part_order_return(dealership_id, returned_at desc, id desc);
