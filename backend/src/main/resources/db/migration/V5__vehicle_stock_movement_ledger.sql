create table vehicle_stock_movement (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  dealership_id bigint not null references dealership(id),
  vehicle_unit_id bigint not null,
  from_status varchar(24) check (
    from_status is null or from_status in ('EXPECTED', 'AVAILABLE', 'RESERVED', 'SOLD', 'RETURNED', 'DAMAGED')
  ),
  to_status varchar(24) not null check (
    to_status in ('EXPECTED', 'AVAILABLE', 'RESERVED', 'SOLD', 'RETURNED', 'DAMAGED')
  ),
  event_type varchar(48) not null check (
    event_type in ('UNIT_REGISTERED', 'STOCK_RECEIVED', 'RESERVED', 'RESERVATION_RELEASED',
      'SOLD', 'SALE_REVERSED', 'RETURNED', 'MARKED_DAMAGED', 'DAMAGE_CLEARED', 'CORRECTION')
  ),
  reference_type varchar(48),
  reference_id varchar(100),
  reason varchar(500),
  actor_staff_user_id bigint,
  created_at timestamptz not null default now(),
  constraint fk_vehicle_movement_unit_same_dealership
    foreign key (dealership_id, vehicle_unit_id)
    references vehicle_unit (dealership_id, id),
  constraint fk_vehicle_movement_actor_same_dealership
    foreign key (dealership_id, actor_staff_user_id)
    references staff_user (dealership_id, id)
);
create index ix_vehicle_movement_unit_history
  on vehicle_stock_movement (dealership_id, vehicle_unit_id, created_at desc);
create index ix_vehicle_movement_dealership_created
  on vehicle_stock_movement (dealership_id, created_at desc);

create table vehicle_model_change_audit (
  id bigint generated by default as identity primary key,
  dealership_id bigint not null references dealership(id),
  vehicle_model_id bigint not null,
  actor_staff_user_id bigint,
  action varchar(48) not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint fk_vehicle_model_audit_model_same_dealership
    foreign key (dealership_id, vehicle_model_id)
    references vehicle_model (dealership_id, id),
  constraint fk_vehicle_model_audit_actor_same_dealership
    foreign key (dealership_id, actor_staff_user_id)
    references staff_user (dealership_id, id)
);
create index ix_vehicle_model_audit_history
  on vehicle_model_change_audit (dealership_id, vehicle_model_id, created_at desc);
